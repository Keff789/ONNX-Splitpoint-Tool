def _find_results_yaml(primary: Path, search_roots: list[Path]) -> Path:
    """Find power_calculations results.yaml robustly.

    Normally power_calculations writes <output_path>/results.yaml.  During
    development or when the binary changes, results may end up in a nested or
    alternative output directory.  We still prefer the intended path, but search
    nearby so diagnostics and summaries do not look empty.
    """
    if primary.exists():
        return primary
    candidates: list[Path] = []
    for root in search_roots:
        try:
            if root.exists():
                candidates.extend(root.rglob("results.yaml"))
                candidates.extend(root.rglob("result.yaml"))
        except Exception:
            pass
    candidates = [c for c in candidates if c.is_file()]
    if not candidates:
        return primary
    candidates.sort(key=lambda x: x.stat().st_mtime if x.exists() else 0, reverse=True)
    return candidates[0]


def _collect_artifact_index(out_dir: Path) -> dict[str, Any]:
    """Create a compact index of generated energy measurement files."""
    files: list[dict[str, Any]] = []
    for path in sorted(out_dir.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(out_dir).as_posix()
        files.append({
            "path": str(path),
            "relative_path": rel,
            "size_bytes": path.stat().st_size,
        })
    by_suffix: dict[str, int] = {}
    for item in files:
        suffix = Path(item["relative_path"]).suffix or "<none>"
        by_suffix[suffix] = by_suffix.get(suffix, 0) + 1
    return {
        "out_dir": str(out_dir),
        "file_count": len(files),
        "files": files,
        "by_suffix": by_suffix,
    }


def _write_artifact_index(out_dir: Path) -> dict[str, Any]:
    idx = _collect_artifact_index(out_dir)
    _write_json(out_dir / "artifact_index.json", idx)
    return idx

def _try_raw_parquet_summary(storage_dir: Path, output_path: Path | None = None) -> dict[str, Any]:
    """Best-effort raw parquet inventory.

    This is deliberately not a calibrated energy calculation.  The Rust
    power_calculations tool remains the source of truth for calibrated u.RECS
    power/energy.  The fallback only records whether parquet files were written
    and, when possible, their columns/row counts for debugging.
    """
    files = sorted(storage_dir.glob("*.parquet"))
    summary: dict[str, Any] = {
        "raw_parquet_present": bool(files),
        "parquet_file_count": len(files),
        "parquet_files": [str(p) for p in files],
        "calibrated_energy_available": False,
        "note": "raw parquet inventory only; install power_calculations for calibrated energy_j/avg_power_w",
    }
    samples: list[dict[str, Any]] = []
    for p in files[:5]:
        item: dict[str, Any] = {"path": str(p), "size_bytes": p.stat().st_size if p.exists() else None}
        try:
            try:
                import pyarrow.parquet as pq  # type: ignore
                meta = pq.ParquetFile(p)
                item["rows"] = meta.metadata.num_rows if meta.metadata else None
                item["columns"] = list(meta.schema.names)
            except Exception:
                import pandas as pd  # type: ignore
                df = pd.read_parquet(p)
                item["rows"] = int(len(df))
                item["columns"] = [str(c) for c in df.columns]
        except Exception as exc:
            item["read_error"] = f"{type(exc).__name__}: {exc}"
        samples.append(item)
    summary["file_summaries"] = samples
    if output_path is not None:
        _write_json(output_path, summary)
    return summary


def write_command_script(path: Path, command: str, cwd: str | Path | None = None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["#!/usr/bin/env bash", "set -euo pipefail"]
    if cwd:
        lines.append("cd " + shlex.quote(str(cwd)))
    lines.append(str(command))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        path.chmod(0o755)
    except Exception:
        pass
    return path


def _write_captured_workload_script(
    path: Path,
    workload_script: Path,
    *,
    stdout_path: Path,
    stderr_path: Path,
    timing_path: Path,
) -> Path:
    """Write the collector command and persist the workload's own output."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "#!/usr/bin/env bash",
        "set -u",
        f"timing_path={shlex.quote(str(timing_path))}",
        "start_ns=$(date +%s%N)",
        "printf 'start_ns=%s\n' \"$start_ns\" > \"$timing_path\"",
        "set +e",
        f"{shlex.quote(str(workload_script))} > {shlex.quote(str(stdout_path))} 2> {shlex.quote(str(stderr_path))}",
        "rc=$?",
        "set -e",
        "end_ns=$(date +%s%N)",
        "printf 'end_ns=%s\nrc=%s\n' \"$end_ns\" \"$rc\" >> \"$timing_path\"",
        "exit \"$rc\"",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        path.chmod(0o755)
    except Exception:
        pass
    return path


def _read_workload_timing(path: Path) -> dict[str, Any]:
    values: dict[str, str] = {}
    try:
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            key, sep, value = line.partition("=")
            if sep:
                values[key.strip()] = value.strip()
        start_ns = int(values.get("start_ns") or 0)
        end_ns = int(values.get("end_ns") or 0)
        duration_s = (end_ns - start_ns) / 1_000_000_000.0 if end_ns >= start_ns > 0 else None
        return {
            "start_ns": start_ns or None,
            "end_ns": end_ns or None,
            "duration_s": duration_s,
            "rc": int(values["rc"]) if values.get("rc") not in (None, "") else None,
            "path": str(path),
            "status": "ok" if duration_s is not None else "unavailable",
        }
    except Exception as exc:
        return {"path": str(path), "status": "unavailable", "error": f"{type(exc).__name__}: {exc}"}


def _canonical_window_label(value: Any) -> str:
    text = str(value or "").strip().lower().replace("-", "_")
    if text in {"command", "command_energy", "command_window"}:
        return "command_window"
    if text in {"trim", "trimmed", "activity", "trimmed_activity_window"}:
        return "trimmed_activity_window"
    if text in {"complete", "complete_window", "complete_measurement_window"}:
        return "complete_measurement_window"
    return text or "unspecified"


def _full_system_scope_calibration_status(
    physical_scope: str,
    calibration_verification: Mapping[str, Any],
    scale_verification: Mapping[str, Any],
    *,
    scale_applied: bool,
    diagnostic_without_manifest: bool = False,
) -> str:
    """Use the verified calibration actually used by this FS capture.

    The scale verifier deliberately accepts an unconfigured identity factor.
    That is safe for arithmetic, but is not evidence of an FS calibration.
    Explicit method-provenance claims are still checked before acquisition.
    """
    if diagnostic_without_manifest:
        return "diagnostic_idle_calibration_not_required"
    if physical_scope not in {"FS", "FULL_SYSTEM"}:
        return "not_full_system"
    if scale_verification.get("full_system_current_scale_configured") is True:
        if (
            scale_verification.get("full_system_current_scale_applicable") is not True
            or scale_verification.get("full_system_current_scale_verified") is not True
        ):
            return "full_system_current_scale_verification_failed"
        if not scale_applied:
            return "full_system_current_scale_not_applied"
        return "pass"
    if calibration_verification.get("verified") is True:
        return "pass"
    return str(calibration_verification.get("status") or "missing")


def _sha256_path(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


