def _student_t_critical(confidence_level: float, degrees_of_freedom: int) -> float:
    """Two-sided quantile, using SciPy or inversion of the regularized beta.

    The dependency-free path evaluates the finite-sample CDF, not an
    asymptotic expansion. Failure to converge never substitutes a normal CI.
    """
    cl = float(confidence_level)
    if not math.isfinite(cl) or not 0.0 < cl < 1.0:
        raise ValueError("confidence_level must be finite and strictly between 0 and 1")
    df = int(degrees_of_freedom)
    if df < 1 or df != degrees_of_freedom:
        raise ValueError("degrees_of_freedom must be a positive integer")
    try:
        from scipy.stats import t
    except ImportError:
        pass
    else:
        return float(t.isf((1.0 - cl) / 2.0, df))
    if df == 1:
        return 1.0 / math.tan(math.pi * (1.0 - cl) / 2.0)
    if df == 2:
        return cl * math.sqrt(2.0 / ((1.0 - cl) * (1.0 + cl)))

    def beta_fraction(a: float, b: float, x: float) -> float:
        # Modified Lentz evaluation of the incomplete-beta continued fraction.
        tiny = 1e-300
        def nonzero(value: float) -> float:
            return value if abs(value) >= tiny else math.copysign(tiny, value)
        c = 1.0
        d = 1.0 / nonzero(1.0 - (a + b) * x / (a + 1.0))
        h = d
        for m in range(1, 1001):
            for aa in (
                m * (b - m) * x / ((a + 2*m - 1) * (a + 2*m)),
                -(a + m) * (a + b + m) * x / ((a + 2*m) * (a + 2*m + 1)),
            ):
                d = 1.0 / nonzero(1.0 + aa * d)
                c = nonzero(1.0 + aa / c)
                delta = d * c
                h *= delta
            if abs(delta - 1.0) < 3e-15:
                return h
        raise ArithmeticError("Student-t incomplete beta did not converge")

    def beta(x: float, a: float, b: float) -> float:
        if x <= 0.0:
            return 0.0
        if x >= 1.0:
            return 1.0
        front = math.exp(math.lgamma(a + b) - math.lgamma(a) - math.lgamma(b)
                         + a * math.log(x) + b * math.log1p(-x))
        if x < (a + 1.0) / (a + b + 2.0):
            return front * beta_fraction(a, b, x) / a
        return 1.0 - front * beta_fraction(b, a, 1.0 - x) / b

    target = 1.0 - cl
    lo, hi = 0.0, 1.0
    def tail(value: float) -> float:
        return beta(df / (df + value * value), df / 2.0, .5)
    while tail(hi) > target:
        hi *= 2.0
    for _ in range(200):
        mid = (lo + hi) / 2.0
        if tail(mid) > target:
            lo = mid
        else:
            hi = mid
        if hi - lo <= 2e-14 * hi:
            return (lo + hi) / 2.0
    raise ArithmeticError("Student-t quantile did not converge")


def _repeat_statistics(values: list[float], confidence_level: float) -> dict[str, Any]:
    if not math.isfinite(float(confidence_level)) or not 0.0 < float(confidence_level) < 1.0:
        raise ValueError("confidence_level must be finite and strictly between 0 and 1")
    vals = [float(value) for value in values if isinstance(value, (int, float)) and math.isfinite(float(value))]
    n = len(vals)
    if not vals:
        return {
            "n": 0,
            "confidence_level": float(confidence_level),
            "mean": None,
            "sample_stddev": None,
            "standard_error": None,
            "ci_low": None,
            "ci_high": None,
            "ci_half_width": None,
            "coefficient_of_variation_percent": None,
            "method": "student_t_two_sided",
        }
    mean = float(statistics.fmean(vals))
    if n < 2:
        return {
            "n": n,
            "confidence_level": float(confidence_level),
            "mean": mean,
            "sample_stddev": None,
            "standard_error": None,
            "ci_low": None,
            "ci_high": None,
            "ci_half_width": None,
            "coefficient_of_variation_percent": None,
            "method": "student_t_two_sided",
            "status": "single_valid_repeat",
        }
    stddev = float(statistics.stdev(vals))
    standard_error = stddev / math.sqrt(n)
    critical = _student_t_critical(confidence_level, n - 1)
    half_width = critical * standard_error
    return {
        "n": n,
        "confidence_level": float(confidence_level),
        "degrees_of_freedom": n - 1,
        "critical_value": critical,
        "mean": mean,
        "sample_stddev": stddev,
        "standard_error": standard_error,
        "ci_low": mean - half_width,
        "ci_high": mean + half_width,
        "ci_half_width": half_width,
        "coefficient_of_variation_percent": (100.0 * stddev / abs(mean)) if mean != 0.0 else None,
        "method": "student_t_two_sided",
        "status": "ok",
    }


def _extract_work_units_from_text_v60i(text: str) -> tuple[int | None, str]:
    """Extract the exact completed-work marker emitted by the runtime wrapper."""
    matches = re.findall(r"__SPLITPOINT_WORK_UNITS__\s*=\s*([0-9]+)", str(text or ""))
    if not matches:
        return None, ""
    try:
        value = int(matches[-1])
    except Exception:
        return None, ""
    if value <= 0:
        return None, ""
    source_match = re.findall(r"__SPLITPOINT_WORK_UNITS_SOURCE__\s*=\s*([^\r\n]+)", str(text or ""))
    source = source_match[-1].strip() if source_match else "runtime_marker"
    return value, source


_EXACT_WORK_UNIT_KEYS = (
    "completed_work_units",
    "completed_frames",
    "frames_completed",
    "measured_frames",
    "consumed_frames",
    "inferences_completed",
)


def _positive_int(value: Any) -> int | None:
    if isinstance(value, bool):
        return None
    try:
        number = float(value)
    except Exception:
        return None
    if not math.isfinite(number) or number <= 0 or not number.is_integer():
        return None
    return int(number)


def _extract_work_unit_evidence(text: str, *, evidence_path: str = "") -> dict[str, Any]:
    """Extract completed-work evidence without mistaking a requested count for it.

    The runtime wrapper emits an explicit marker and an exactness marker.  Older
    wrappers did not emit the latter, therefore their source string is inspected:
    completed/measured/consumed fields are exact, whereas a bare ``frames`` field
    is retained as diagnostic evidence only.  Direct JSON output is accepted only
    for unambiguously completed-count field names.
    """
    raw = str(text or "")
    count, source = _extract_work_units_from_text_v60i(raw)
    exact_matches = re.findall(r"__SPLITPOINT_WORK_UNITS_EXACT__\s*=\s*([01])", raw)
    exact: bool | None = bool(int(exact_matches[-1])) if exact_matches else None
    if count is not None:
        source_l = str(source or "").lower()
        if exact is None:
            exact = source == "runtime_marker" or any(f"json_field:{key}" in source_l for key in _EXACT_WORK_UNIT_KEYS)
        return {
            "count": count,
            "source": source or "runtime_marker",
            "exact": bool(exact),
            "transport": "runtime_marker",
            "evidence_path": evidence_path,
        }

    # A runner may write a compact JSON result directly without the wrapper.
    # Only explicit completion fields are eligible here; ``frames`` and
    # ``inference_count`` are intentionally excluded because they often mean the
    # requested/configured count.
    candidates: list[tuple[int, str]] = []
    for key in _EXACT_WORK_UNIT_KEYS:
        pattern = re.compile(r'"' + re.escape(key) + r'"\s*:\s*([-+0-9.eE]+)')
        for value in pattern.findall(raw):
            parsed = _positive_int(value)
            if parsed is not None:
                candidates.append((parsed, key))
    if candidates:
        value, key = candidates[-1]
        return {
            "count": value,
            "source": f"workload_json_field:{key}",
            "exact": True,
            "transport": "workload_output",
            "evidence_path": evidence_path,
        }
    return {"count": None, "source": "", "exact": False, "transport": "", "evidence_path": evidence_path}


def _sidecar_work_unit_evidence(path: Path) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {"count": None, "source": "", "exact": False, "transport": "", "evidence_path": str(path)}

    def walk(value: Any) -> tuple[int | None, str]:
        if isinstance(value, Mapping):
            for key in _EXACT_WORK_UNIT_KEYS:
                if key in value:
                    parsed = _positive_int(value.get(key))
                    if parsed is not None:
                        return parsed, key
            # A dedicated sidecar may use the canonical neutral ``count`` key,
            # but it must explicitly assert exact completion semantics.
            if value.get("exact") is True:
                parsed = _positive_int(value.get("count") or value.get("work_units"))
                if parsed is not None:
                    return parsed, "sidecar_exact_count"
            for child in value.values():
                found, source = walk(child)
                if found is not None:
                    return found, source
        elif isinstance(value, list):
            for child in value:
                found, source = walk(child)
                if found is not None:
                    return found, source
        return None, ""

    count, source = walk(payload)
    return {
        "count": count,
        "source": f"sidecar:{source}" if source else "",
        "exact": count is not None,
        "transport": "sidecar",
        "evidence_path": str(path),
    }


def _runtime_work_unit_evidence(run_dir: Path) -> dict[str, Any]:
    """Resolve exact work units from sidecars, captured workload output or collector logs."""
    sidecar_names = (
        "workload_work_units.json",
        "work_units.json",
        "run_and_report_work_units.json",
        "runtime_completed_work_units.json",
    )
    evidence: list[dict[str, Any]] = []
    for name in sidecar_names:
        path = run_dir / name
        if path.is_file():
            evidence.append(_sidecar_work_unit_evidence(path))
    for name in ("workload_stdout.log", "workload_stderr.log", "collector_stdout.log", "collector_stderr.log"):
        path = run_dir / name
        if path.is_file():
            evidence.append(_extract_work_unit_evidence(_tail_text(path, 2_000_000), evidence_path=str(path)))
    available = [item for item in evidence if _positive_int(item.get("count")) is not None]
    if not available:
        return {
            "count": None,
            "source": "",
            "exact": False,
            "transport": "unavailable",
            "evidence_path": "",
            "status": "unavailable",
        }
    # Prefer exact sidecars, then exact captured workload output, then legacy
    # diagnostic markers.  Never use a larger count merely because it is larger.
    priority = {"sidecar": 0, "workload_output": 1, "runtime_marker": 2, "": 4}
    best = sorted(
        available,
        key=lambda item: (0 if item.get("exact") else 1, priority.get(str(item.get("transport") or ""), 3)),
    )[0]
    return {**best, "status": "exact" if best.get("exact") else "unverified"}


def _runtime_work_units_v60i(stdout_path: Path, stderr_path: Path) -> tuple[int | None, str]:
    """Backward-compatible two-file parser retained for external callers/tests."""
    combined = "\n".join((_tail_text(stdout_path, 200000), _tail_text(stderr_path, 200000)))
    return _extract_work_units_from_text_v60i(combined)


