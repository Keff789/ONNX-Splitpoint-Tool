def _verify_calibration_manifest(
    manifest: str | Path | None,
    declared_sha256: str | None,
    *,
    setup_id: str | None = None,
    urecs_address: str | None = None,
    data_port: int | None = None,
    channel: int | None = None,
    sample_rate_hz: int | None = None,
    physical_scope: str | None = None,
    collector_mode: str | None = None,
    collector_binary: str | None = None,
    postprocessor_binary: str | None = None,
    expected_channel_bindings: Sequence[Mapping[str, Any]] | None = None,
) -> dict[str, Any]:
    """Verify the local energy-evidence artefact and its runtime binding.

    Historical/direct-calibration manifests retain their original local-file
    and SHA-256 contract.  A v2 ``inherited_validated_method`` manifest is a
    stronger contract: its complete content is verified with the campaign
    verifier and the selected setup, u.RECS endpoint, UDP data port, channel,
    sample rate, physical scope and implementation mode must match one locked
    binding.

    The optional runtime arguments keep direct callers backwards compatible.
    They are mandatory for inherited evidence, which therefore cannot be
    promoted merely because a correctly hashed JSON file was supplied.
    """
    raw_path = str(manifest or "").strip()
    declared_raw = str(declared_sha256 or "").strip().lower()
    declared = declared_raw.split(":", 1)[1] if declared_raw.startswith("sha256:") else declared_raw
    result: dict[str, Any] = {
        "path": raw_path,
        "declared_sha256": declared,
        "declared_sha256_input": declared_raw,
        "actual_sha256": "",
        "verified": False,
        "status": "missing",
        "evidence_mode": "",
        "runtime_fail_closed_required": False,
        "inherited_content_verified": False,
        "inherited_binding_verified": False,
        "runtime_binding_id": "",
        "runtime_binding_errors": [],
    }
    if not raw_path:
        return result
    if "://" in raw_path:
        result["status"] = "external_attestation_not_locally_verifiable"
        return result
    path = Path(raw_path).expanduser()
    if not path.is_file():
        result["status"] = "manifest_file_missing"
        return result
    try:
        raw_bytes = path.read_bytes()
    except Exception as exc:
        result["status"] = "manifest_read_failed"
        result["error"] = f"{type(exc).__name__}: {exc}"
        return result
    actual = hashlib.sha256(raw_bytes).hexdigest()
    result["actual_sha256"] = actual
    payload: dict[str, Any] | None = None
    try:
        loaded = json.loads(raw_bytes.decode("utf-8"))
        if isinstance(loaded, Mapping):
            payload = dict(loaded)
    except Exception as exc:
        # A historical direct-calibration artefact was previously opaque to
        # this runtime helper.  Preserve that compatibility while recording
        # the parse diagnostic.  Only an explicit inherited contract activates
        # the new fail-closed content/binding gate.
        result["manifest_json_error"] = f"{type(exc).__name__}: {exc}"
    evidence_mode = str(
        (payload or {}).get("evidence_mode") or "direct_calibration"
    ).strip().lower()
    result["evidence_mode"] = evidence_mode
    result["runtime_fail_closed_required"] = bool(
        evidence_mode != "direct_calibration"
    )
    if re.fullmatch(r"[0-9a-f]{64}", declared) is None:
        result["status"] = "declared_sha256_missing_or_invalid"
        return result
    if actual != declared:
        result["status"] = "sha256_mismatch"
        return result

    if evidence_mode == "direct_calibration":
        result["verified"] = True
        result["status"] = "verified"
        result["path"] = str(path.resolve())
        return result

    if evidence_mode != "inherited_validated_method":
        result["status"] = "unsupported_energy_evidence_mode"
        return result
    if payload is None:
        result["status"] = "inherited_method_manifest_json_invalid"
        return result

    expected_bindings = [
        dict(row)
        for row in list(expected_channel_bindings or [])
        if isinstance(row, Mapping)
    ]
    result["expected_channel_binding_count"] = len(expected_bindings)
    if not expected_bindings:
        result["status"] = "inherited_method_expected_channel_bindings_missing"
        result["runtime_binding_errors"] = [
            "runtime_expected_channel_bindings_missing"
        ]
        return result

    binding_source = next(
        (
            (payload.get(key), key)
            for key in ("channel_bindings", "bindings", "target_bindings")
            if isinstance(payload.get(key), list)
        ),
        ([], ""),
    )
    raw_bindings, binding_source_key = binding_source
    bindings = [
        dict(row) for row in list(raw_bindings or [])
        if isinstance(row, Mapping)
    ]
    manifest_method = (
        dict(payload.get("method") or {})
        if isinstance(payload.get("method"), Mapping)
        else {}
    )
    # A claim-bearing inherited manifest is admitted only through the current
    # exact method contract.  Reject an absent/non-list binding container and
    # every non-mapping row before any filtering or canonical projection can
    # hide it.  The configured-method admission below additionally requires
    # the exact seven binding fields and exact eight implementation artefacts.
    raw_binding_rows_exact = bool(
        binding_source_key == "channel_bindings"
        and isinstance(raw_bindings, list)
        and len(bindings) == len(raw_bindings)
    )
    result["raw_channel_binding_rows_exact"] = raw_binding_rows_exact
    if not raw_binding_rows_exact:
        result["status"] = "inherited_method_manifest_invalid"
        result["runtime_binding_errors"] = [
            "runtime_channel_binding_rows_not_exact"
        ]
        return result

    verification_payload = payload

    # Import locally to avoid making the low-level collector depend on the
    # campaign module during normal/direct measurements.  The shared verifier
    # is authoritative for schema, payload/binding-set hashes, implementation
    # artefact hashes, validation reference and reuse attestation.
    try:
        from ..campaign import verify_energy_calibration_manifest
        from ..workflow.artifacts import sha256_json

        # ``channel_bindings`` is canonical.  The two historical aliases are
        # accepted only after their *original* payload and binding-set hashes
        # verify.  A canonical in-memory projection is then passed to the
        # shared schema verifier; this does not weaken or rewrite the persisted
        # evidence artefact.
        if binding_source_key in {"bindings", "target_bindings"}:
            unsigned = {
                key: value for key, value in payload.items()
                if key != "manifest_payload_sha256"
            }
            original_payload_hash_ok = str(
                payload.get("manifest_payload_sha256") or ""
            ) == sha256_json(unsigned)
            original_binding_hash = str(
                payload.get("channel_binding_set_sha256")
                or payload.get("binding_set_sha256")
                or payload.get("target_binding_set_sha256")
                or ""
            )
            original_binding_hash_ok = (
                original_binding_hash == sha256_json(bindings)
            )
            result["alias_payload_hash_ok"] = original_payload_hash_ok
            result["alias_binding_set_hash_ok"] = (
                original_binding_hash_ok
            )
            if not original_payload_hash_ok or not original_binding_hash_ok:
                result["status"] = (
                    "inherited_method_alias_manifest_hash_invalid"
                )
                return result
            verification_payload = dict(payload)
            verification_payload.pop("bindings", None)
            verification_payload.pop("target_bindings", None)
            verification_payload.pop("binding_set_sha256", None)
            verification_payload.pop("target_binding_set_sha256", None)
            verification_payload["channel_bindings"] = bindings
            verification_payload["channel_binding_set_sha256"] = (
                sha256_json(bindings)
            )
            verification_payload["manifest_payload_sha256"] = sha256_json(
                {
                    key: value
                    for key, value in verification_payload.items()
                    if key != "manifest_payload_sha256"
                }
            )

        content_verification = verify_energy_calibration_manifest(
            verification_payload,
            require_final=True,
            expected_channel_bindings=expected_bindings,
        )
    except Exception as exc:
        result["status"] = "inherited_method_manifest_verification_failed"
        result["error"] = f"{type(exc).__name__}: {exc}"
        return result
    result["inherited_content_verification"] = content_verification
    binding_fields = (
        "setup_id",
        "urecs_address",
        "data_port",
        "channel",
        "sample_rate_hz",
        "scope",
        "measurement_point",
    )

    def _exact_binding_projection(
        source: Sequence[Mapping[str, Any]],
    ) -> list[dict[str, Any]]:
        return sorted(
            [
                {key: row.get(key) for key in binding_fields}
                for row in source
            ],
            key=lambda row: str(row.get("setup_id") or ""),
        )

    exact_expected_bindings_ok = bool(
        _exact_binding_projection(bindings)
        == _exact_binding_projection(expected_bindings)
    )
    result["expected_channel_bindings_exact"] = exact_expected_bindings_ok
    result["expected_channel_binding_projection"] = (
        _exact_binding_projection(expected_bindings)
    )
    result["inherited_content_verified"] = bool(
        content_verification.get("ok") and exact_expected_bindings_ok
    )
    if not result["inherited_content_verified"]:
        if not exact_expected_bindings_ok:
            result["runtime_binding_errors"] = [
                "runtime_expected_channel_binding_set_mismatch"
            ]
        result["status"] = "inherited_method_manifest_invalid"
        return result

    def _normalise_scope(value: Any) -> str:
        return str(value or "").strip().upper().replace("-", "_")

    def _normalise_mode(value: Any) -> str:
        return str(value or "").strip().lower().replace("-", "_")

    def _strict_runtime_int(value: Any) -> int | None:
        if isinstance(value, bool):
            return None
        try:
            parsed = int(value)
        except Exception:
            return None
        try:
            if float(value) != float(parsed):
                return None
        except Exception:
            return None
        return parsed

    actual_setup_id = str(setup_id or "").strip()
    actual_address = str(urecs_address or "").strip()
    actual_data_port = _strict_runtime_int(data_port)
    actual_channel = _strict_runtime_int(channel)
    actual_sample_rate = _strict_runtime_int(sample_rate_hz)
    actual_scope = _normalise_scope(physical_scope)
    actual_mode = _normalise_mode(collector_mode)
    actual_collector = Path(str(collector_binary or "").strip()).name
    actual_postprocessor = Path(
        str(postprocessor_binary or "").strip()
    ).name

    setup_matches = [
        row for row in bindings
        if str(row.get("setup_id") or "").strip() == actual_setup_id
    ]
    errors: list[str] = []
    if not actual_setup_id:
        errors.append("runtime_setup_id_missing")
    if not actual_address:
        errors.append("runtime_urecs_address_missing")
    if actual_channel != 0:
        errors.append("runtime_channel_not_zero")
    if actual_sample_rate != 2000:
        errors.append("runtime_sample_rate_not_2000_hz")
    if actual_scope not in {"FS", "FULL_SYSTEM"}:
        errors.append("runtime_physical_scope_not_full_system")
    if actual_mode != "fast_firmware":
        errors.append("runtime_collector_mode_not_fast_firmware")

    method = (
        dict(payload.get("method") or {})
        if isinstance(payload.get("method"), Mapping)
        else {}
    )
    expected_collector = Path(
        str(method.get("collector") or "").strip()
    ).name
    expected_postprocessor = Path(
        str(method.get("postprocessor") or "").strip()
    ).name
    method_policy = str(method.get("implementation_policy") or "").strip()
    method_data_port = _strict_runtime_int(method.get("data_port"))
    data_port_binding_required = bool(
        method_policy == "exact_validated_implementation_reuse"
        or "data_port" in method
        or any("data_port" in row for row in bindings)
    )
    result["runtime_data_port"] = actual_data_port
    result["manifest_method_data_port"] = method_data_port
    result["runtime_data_port_binding_required"] = (
        data_port_binding_required
    )
    if data_port_binding_required:
        if actual_data_port is None or not 1 <= actual_data_port <= 65535:
            errors.append("runtime_data_port_missing_or_invalid")
        if method_data_port is None or not 1 <= method_data_port <= 65535:
            errors.append("manifest_method_data_port_missing_or_invalid")
        elif method_data_port != actual_data_port:
            errors.append("runtime_data_port_method_mismatch")
    if actual_collector != expected_collector:
        errors.append("runtime_collector_binary_mismatch")
    if actual_postprocessor != expected_postprocessor:
        errors.append("runtime_postprocessor_binary_mismatch")

    # An exact validated-method reuse contract binds executable *content*, not
    # merely an argv basename.  Resolving the active executable again at this
    # final preflight catches a PATH change where an unrelated binary has the
    # same filename as the one hashed into the manifest.  Older inherited
    # manifests that predate ``implementation_policy`` remain readable; every
    # current exact-reuse manifest is fail-closed and must carry both canonical
    # binary artefact IDs.
    artifacts = [
        dict(row)
        for row in list(payload.get("artifacts") or [])
        if isinstance(row, Mapping)
    ]
    artifact_ids = {
        str(row.get("id") or "").strip() for row in artifacts
    }
    canonical_binary_ids = {
        "urecs_data_collector_binary",
        "power_calculations_binary",
    }
    binary_provenance_required = bool(
        method_policy == "exact_validated_implementation_reuse"
        or canonical_binary_ids & artifact_ids
    )
    result["runtime_binary_provenance_required"] = (
        binary_provenance_required
    )
    binary_verification: dict[str, Any] = {}

    def _normalise_digest(value: Any) -> str:
        digest = str(value or "").strip().lower()
        return digest.split(":", 1)[1] if digest.startswith("sha256:") else digest

    def _resolve_active_executable(value: Any) -> tuple[Path | None, str]:
        requested = str(value or "").strip()
        if not requested:
            return None, "not_configured"
        expanded = _expand_binary(requested)
        candidate = Path(expanded).expanduser()
        if not candidate.is_absolute() and not any(
            separator in expanded for separator in ("/", "\\")
        ):
            resolved = _which_energy(expanded) or shutil.which(expanded)
            if not resolved:
                return None, "not_found"
            candidate = Path(resolved)
        try:
            candidate = candidate.resolve(strict=True)
        except (FileNotFoundError, OSError):
            return None, "not_found"
        if not candidate.is_file():
            return None, "not_regular_file"
        if not os.access(candidate, os.X_OK):
            return None, "not_executable"
        return candidate, "resolved"

    binary_roles = (
        (
            "collector",
            "urecs_data_collector_binary",
            collector_binary,
            "runtime_collector_binary",
        ),
        (
            "postprocessor",
            "power_calculations_binary",
            postprocessor_binary,
            "runtime_postprocessor_binary",
        ),
    )
    for role, artifact_id, requested_binary, error_prefix in binary_roles:
        report: dict[str, Any] = {
            "artifact_id": artifact_id,
            "requested": str(requested_binary or ""),
            "resolved_path": "",
            "manifest_path": "",
            "manifest_sha256": "",
            "actual_sha256": "",
            "path_match": False,
            "sha256_match": False,
            "verified": False,
            "required": binary_provenance_required,
        }
        if not binary_provenance_required:
            report["status"] = "legacy_not_required"
            binary_verification[role] = report
            continue
        matches = [
            row
            for row in artifacts
            if str(row.get("id") or "").strip() == artifact_id
        ]
        if len(matches) != 1:
            reason = (
                f"{error_prefix}_artifact_missing"
                if not matches
                else f"{error_prefix}_artifact_ambiguous"
            )
            errors.append(reason)
            report["status"] = reason
            binary_verification[role] = report
            continue
        artifact = matches[0]
        manifest_binary_raw = str(artifact.get("path") or "").strip()
        manifest_digest = _normalise_digest(artifact.get("sha256"))
        report["manifest_path"] = manifest_binary_raw
        report["manifest_sha256"] = manifest_digest
        active_path, resolution_status = _resolve_active_executable(
            requested_binary
        )
        if active_path is None:
            reason = f"{error_prefix}_{resolution_status}"
            errors.append(reason)
            report["status"] = reason
            binary_verification[role] = report
            continue
        report["resolved_path"] = str(active_path)
        try:
            manifest_binary = Path(manifest_binary_raw).expanduser().resolve(
                strict=True
            )
        except (FileNotFoundError, OSError):
            reason = f"{error_prefix}_artifact_path_unavailable"
            errors.append(reason)
            report["status"] = reason
            binary_verification[role] = report
            continue
        report["manifest_path"] = str(manifest_binary)
        report["path_match"] = active_path == manifest_binary
        if not report["path_match"]:
            errors.append(f"{error_prefix}_artifact_path_mismatch")
        try:
            active_digest = _sha256_path(active_path)
        except OSError:
            active_digest = ""
        report["actual_sha256"] = active_digest
        report["sha256_match"] = bool(
            re.fullmatch(r"[0-9a-f]{64}", manifest_digest)
            and active_digest == manifest_digest
        )
        if not report["sha256_match"]:
            errors.append(f"{error_prefix}_artifact_sha256_mismatch")
        report["verified"] = bool(
            report["path_match"] and report["sha256_match"]
        )
        report["status"] = "verified" if report["verified"] else "mismatch"
        binary_verification[role] = report
    result["runtime_binary_verification"] = binary_verification

    if len(setup_matches) == 0:
        errors.append("runtime_setup_binding_missing")
    elif len(setup_matches) > 1:
        errors.append("runtime_setup_binding_ambiguous")
    else:
        binding = setup_matches[0]
        result["runtime_binding_id"] = str(
            binding.get("binding_id") or binding.get("setup_id") or ""
        ).strip()
        bound_address = str(binding.get("urecs_address") or "").strip()
        bound_channel = _strict_runtime_int(binding.get("channel"))
        bound_data_port = _strict_runtime_int(binding.get("data_port"))
        result["manifest_binding_data_port"] = bound_data_port
        bound_sample_rate = _strict_runtime_int(
            binding.get("sample_rate_hz", method.get("sample_rate_hz"))
        )
        bound_scope = _normalise_scope(
            binding.get("scope", payload.get("scope"))
        )
        if bound_address != actual_address:
            errors.append("runtime_urecs_address_binding_mismatch")
        if data_port_binding_required:
            if bound_data_port is None or not 1 <= bound_data_port <= 65535:
                errors.append("manifest_binding_data_port_missing_or_invalid")
            elif bound_data_port != actual_data_port:
                errors.append("runtime_data_port_binding_mismatch")
        if bound_channel != actual_channel:
            errors.append("runtime_channel_binding_mismatch")
        if bound_sample_rate != actual_sample_rate:
            errors.append("runtime_sample_rate_binding_mismatch")
        if bound_scope not in {"FS", "FULL_SYSTEM"}:
            errors.append("manifest_binding_scope_not_full_system")
        elif bound_scope != actual_scope and not (
            bound_scope == "FS" and actual_scope == "FULL_SYSTEM"
        ) and not (
            bound_scope == "FULL_SYSTEM" and actual_scope == "FS"
        ):
            errors.append("runtime_physical_scope_binding_mismatch")

    result["runtime_binding_source"] = binding_source_key
    result["runtime_binding_errors"] = errors
    result["inherited_binding_verified"] = not errors
    if errors:
        result["status"] = "inherited_method_runtime_binding_mismatch"
        return result

    try:
        # Import lazily: method_manifest uses this low-level verifier for its
        # own registry preflight, so a top-level import would create a cycle.
        from .config import EnergyDefaults
        from .method_manifest import _strict_configured_method_admission

        def _strict_int_or_invalid(value: Any) -> int:
            if isinstance(value, bool) or not isinstance(value, int):
                return -1
            return value

        exact_admission = _strict_configured_method_admission(
            path,
            defaults=EnergyDefaults(
                collector_binary=str(collector_binary or ""),
                power_calculations_binary=str(
                    postprocessor_binary or ""
                ),
                mode=str(collector_mode or ""),
                data_port=_strict_int_or_invalid(data_port),
                channel=_strict_int_or_invalid(channel),
                sample_rate=_strict_int_or_invalid(sample_rate_hz),
            ),
            expected_channel_bindings=expected_bindings,
        )
    except Exception as exc:
        result["status"] = "inherited_method_manifest_invalid"
        result["configured_method_admission"] = {
            "ok": False,
            "errors": [
                "configured_method_exact_admission_exception:"
                f"{type(exc).__name__}"
            ],
        }
        result["error"] = f"{type(exc).__name__}: {exc}"
        return result
    result["configured_method_admission"] = exact_admission
    result["configured_method_admission_errors"] = list(
        exact_admission.get("errors") or []
    )
    if not exact_admission.get("ok"):
        result["status"] = "inherited_method_manifest_invalid"
        result["runtime_binding_errors"] = [
            "runtime_exact_configured_method_admission_failed"
        ]
        result["inherited_binding_verified"] = False
        return result
    result["verified"] = True
    result["status"] = "inherited_validated_method_verified"
    result["path"] = str(path.resolve())
    return result


def _find_mapping(value: Any, keys: set[str]) -> Mapping[str, Any] | None:
    if isinstance(value, Mapping):
        for key, item in value.items():
            if str(key) in keys and isinstance(item, Mapping):
                return item
        for item in value.values():
            found = _find_mapping(item, keys)
            if found is not None:
                return found
    elif isinstance(value, list):
        for item in value:
            found = _find_mapping(item, keys)
            if found is not None:
                return found
    return None


def _command_window_binding_v2(
    payload: Mapping[str, Any],
    *,
    manifest_path: Path | None,
    result_data: Mapping[str, Any],
    timing: Mapping[str, Any],
    result_path: Path | None,
) -> dict[str, Any]:
    """Validate a sample-marker crop and every local artefact in its chain."""
    result: dict[str, Any] = {
        "verified": False,
        # Retain the old key for downstream compatibility.  In v2 it means
        # calibrated, unsubtracted input energy, not uncalibrated ADC energy.
        "raw_input_energy_verified": False,
        "calibrated_input_energy_unsubtracted_verified": False,
        "status": "invalid",
        "manifest_path": str(manifest_path or ""),
        "binding_method": str(payload.get("binding_method") or ""),
        "binding_schema_version": 2,
    }

    def fail(status: str, **evidence: Any) -> dict[str, Any]:
        result.update(evidence)
        result["status"] = status
        return result

    if manifest_path is None:
        return fail("v2_binding_manifest_path_missing")
    if payload.get("schema") != _COMMAND_WINDOW_BINDING_SCHEMA_V2 or _strict_int(payload.get("schema_version")) != 2:
        return fail("v2_binding_schema_invalid")
    if str(payload.get("binding_method") or "") != _COMMAND_WINDOW_BINDING_METHOD_V2:
        return fail("unsupported_binding_method")

    artefacts: dict[str, Path] = {}
    hashes: dict[str, str] = {}
    for name in (
        "request",
        "marker",
        "trace",
        "command",
        "workload_command",
        "timing",
        "postprocessor_result",
        "result",
    ):
        raw_path = payload.get(f"{name}_path")
        declared = str(payload.get(f"{name}_sha256") or "").strip().lower()
        if re.fullmatch(r"[0-9a-f]{64}", declared) is None:
            return fail(f"{name}_sha256_missing_or_invalid")
        path = _resolve_artifact_path(raw_path, relative_to=manifest_path.parent)
        if path is None or not path.is_file():
            return fail(f"{name}_file_missing", **{f"{name}_path": str(path or "")})
        try:
            actual = _sha256_path(path)
        except Exception as exc:
            return fail(f"{name}_read_failed", error=f"{type(exc).__name__}: {exc}")
        result[f"{name}_path"] = str(path.resolve())
        result[f"{name}_sha256"] = actual
        if actual != declared:
            return fail(f"{name}_sha256_mismatch")
        artefacts[name] = path
        hashes[name] = actual

    if result_path is None:
        return fail("selected_result_path_missing")
    try:
        if artefacts["result"].resolve() != Path(result_path).resolve():
            return fail("bound_result_is_not_selected_result")
    except Exception:
        return fail("bound_result_path_compare_failed")

    request = _read_json_mapping(artefacts["request"])
    marker = _read_json_mapping(artefacts["marker"])
    post = _read_json_mapping(artefacts["postprocessor_result"])
    if request is None:
        return fail("request_json_invalid")
    if marker is None:
        return fail("marker_json_invalid")
    if post is None:
        return fail("postprocessor_result_json_invalid")
    if request.get("schema") != _COMMAND_WINDOW_REQUEST_SCHEMA_V2 or _strict_int(request.get("schema_version")) != 2:
        return fail("request_schema_invalid")
    if marker.get("schema") != _COMMAND_WINDOW_MARKER_SCHEMA_V2 or _strict_int(marker.get("schema_version")) != 2:
        return fail("marker_schema_invalid")
    if post.get("schema") != _POSTPROCESSOR_WINDOW_RESULT_SCHEMA_V2 or _strict_int(post.get("schema_version")) != 2:
        return fail("postprocessor_result_schema_invalid")
    if str(post.get("status") or "").strip().lower() not in {"ok", "verified"}:
        return fail("postprocessor_result_status_not_ok")

    # The postprocessor must echo the hashes it consumed.  This prevents a
    # valid output JSON from being paired with a different request or trace.
    for name in ("marker", "trace", "command", "workload_command", "timing"):
        expected = hashes[name]
        request_declared = str(request.get(f"{name}_sha256") or "").strip().lower()
        if request_declared != expected:
            return fail(f"request_{name}_sha256_mismatch")
    for name in ("request", "marker", "trace", "command", "timing"):
        expected = hashes[name]
        post_declared = str(post.get(f"{name}_sha256") or "").strip().lower()
        if post_declared != expected:
            return fail(f"postprocessor_{name}_sha256_mismatch")
    for name in ("marker", "trace", "command", "workload_command", "timing"):
        request_artifact_path = _resolve_artifact_path(
            request.get(f"{name}_path"), relative_to=artefacts["request"].parent
        )
        if request_artifact_path is None or request_artifact_path.resolve() != artefacts[name].resolve():
            return fail(f"request_{name}_path_mismatch")
    for name in ("request", "marker", "trace", "command", "timing"):
        post_artifact_path = _resolve_artifact_path(
            post.get(f"{name}_path"), relative_to=artefacts["postprocessor_result"].parent
        )
        if post_artifact_path is None or post_artifact_path.resolve() != artefacts[name].resolve():
            return fail(f"postprocessor_{name}_path_mismatch")
    post_results_path = _resolve_artifact_path(
        post.get("results_path"), relative_to=artefacts["postprocessor_result"].parent
    )
    if post_results_path is None or post_results_path.resolve() != artefacts["result"].resolve():
        return fail("postprocessor_results_path_mismatch")

    run_id = str(request.get("run_id") or "").strip()
    window_id = str(request.get("window_id") or "").strip()
    if not run_id or not window_id:
        return fail("request_run_or_window_id_missing")
    for name, source in (("binding", payload), ("marker", marker), ("postprocessor", post)):
        if str(source.get("run_id") or "").strip() != run_id:
            return fail(f"{name}_run_id_mismatch")
        if str(source.get("window_id") or "").strip() != window_id:
            return fail(f"{name}_window_id_mismatch")

    command = marker.get("command") if isinstance(marker.get("command"), Mapping) else {}
    stream = marker.get("stream") if isinstance(marker.get("stream"), Mapping) else {}
    marker_argv = command.get("argv") if isinstance(command.get("argv"), list) else []
    marker_command_path = _resolve_artifact_path(
        marker_argv[0] if marker_argv else command.get("text"),
        relative_to=artefacts["marker"].parent,
    )
    if marker_command_path is None:
        return fail("marker_command_path_missing")
    try:
        if marker_command_path.resolve() != artefacts["command"].resolve():
            return fail("marker_command_path_mismatch")
    except Exception:
        return fail("marker_command_path_compare_failed")
    if marker.get("valid_for_final_energy") is not True or request.get("valid_for_final_energy") is not True:
        return fail(
            "marker_not_valid_for_final_energy",
            validation_errors=marker.get("validation_errors"),
        )
    marker_validation_errors = marker.get("validation_errors")
    if isinstance(marker_validation_errors, list) and marker_validation_errors:
        return fail("marker_validation_errors_present", validation_errors=marker_validation_errors)
    process_pid = _strict_int(command.get("process_id", command.get("pid")), minimum=1)
    if process_pid is None or _strict_int(request.get("process_id"), minimum=1) != process_pid:
        return fail("process_pid_missing_or_mismatch")
    if _strict_int(post.get("command_process_id"), minimum=1) != process_pid:
        return fail("postprocessor_process_id_mismatch")
    if _strict_int(payload.get("command_process_id"), minimum=1) != process_pid:
        return fail("binding_process_id_mismatch")
    if command.get("process_error") not in (None, "") or request.get("process_error") not in (None, ""):
        return fail("process_error_present")
    for edge in ("start", "end"):
        uncertainty_ns = _strict_int(command.get(f"{edge}_clock_read_uncertainty_ns"), minimum=0)
        if uncertainty_ns is None:
            return fail(f"marker_{edge}_clock_read_uncertainty_missing")
        if _strict_int(request.get(f"{edge}_clock_read_uncertainty_ns"), minimum=0) != uncertainty_ns:
            return fail(f"request_{edge}_clock_read_uncertainty_mismatch")
        for source_name, source in (("postprocessor", post), ("binding", payload)):
            field = f"command_{edge}_clock_read_uncertainty_ns"
            if _strict_int(source.get(field), minimum=0) != uncertainty_ns:
                return fail(f"{source_name}_{edge}_clock_read_uncertainty_mismatch")
    if str(stream.get("source") or "").strip().lower() != "fast_firmware":
        return fail("marker_source_not_fast_firmware")
    for source_name, source in (("request", request), ("binding", payload), ("postprocessor", post)):
        if str(source.get("source") or "").strip().lower() != "fast_firmware":
            return fail(f"{source_name}_source_mismatch")

    process_rc = _strict_int(command.get("process_rc"))
    timing_rc = _strict_int(timing.get("rc"))
    request_rc = _strict_int(request.get("process_rc"))
    post_rc = _strict_int(post.get("process_rc"))
    binding_rc = _strict_int(payload.get("process_rc"))
    if None in {process_rc, timing_rc, request_rc, post_rc, binding_rc}:
        return fail("process_rc_missing")
    if len({process_rc, timing_rc, request_rc, post_rc, binding_rc}) != 1 or process_rc != 0:
        return fail(
            "process_rc_nonzero_or_mismatch",
            marker_process_rc=process_rc,
            timing_rc=timing_rc,
            request_process_rc=request_rc,
            postprocessor_process_rc=post_rc,
            binding_process_rc=binding_rc,
        )

    # Both clocks remain provenance diagnostics for Fast Firmware.  Cropping is
    # based on sample markers, but malformed or reversed command intervals are
    # still rejected.
    for prefix in ("realtime", "monotonic"):
        start = _strict_int(command.get(f"start_{prefix}_ns"), minimum=1)
        end = _strict_int(command.get(f"end_{prefix}_ns"), minimum=1)
        if start is None or end is None or end <= start:
            return fail(f"marker_command_{prefix}_interval_invalid")
        result[f"command_start_{prefix}_ns"] = start
        result[f"command_end_{prefix}_ns"] = end
        for source_name, source in (("request", request), ("postprocessor", post), ("binding", payload)):
            if _strict_int(source.get(f"command_start_{prefix}_ns"), minimum=1) != start:
                return fail(f"{source_name}_command_start_{prefix}_ns_mismatch")
            if _strict_int(source.get(f"command_end_{prefix}_ns"), minimum=1) != end:
                return fail(f"{source_name}_command_end_{prefix}_ns_mismatch")
    timing_start = _strict_int(timing.get("start_ns"), minimum=1)
    timing_end = _strict_int(timing.get("end_ns"), minimum=1)
    marker_realtime_start = _strict_int(command.get("start_realtime_ns"), minimum=1)
    marker_realtime_end = _strict_int(command.get("end_realtime_ns"), minimum=1)
    if None in {timing_start, timing_end, marker_realtime_start, marker_realtime_end}:
        return fail("workload_timing_interval_missing")
    if not (
        marker_realtime_start <= timing_start < timing_end <= marker_realtime_end
    ):
        return fail(
            "workload_timing_not_enclosed_by_collector_command",
            marker_start_realtime_ns=marker_realtime_start,
            workload_start_realtime_ns=timing_start,
            workload_end_realtime_ns=timing_end,
            marker_end_realtime_ns=marker_realtime_end,
        )

    marker_first = _strict_int(stream.get("first_sample_index"), minimum=0)
    marker_last = _strict_int(stream.get("last_sample_index"), minimum=0)
    total_samples = _strict_int(stream.get("total_samples"), minimum=1)
    if marker_first is None or marker_last is None or marker_last <= marker_first:
        return fail("marker_bounds_invalid")
    if total_samples is None or marker_last >= total_samples:
        return fail("marker_trace_coverage_invalid")
    expected_sample_count = marker_last - marker_first + 1
    expected_interval_count = marker_last - marker_first
    marker_rate = _finite_float(stream.get("sample_rate_hz"), minimum=0.0)
    if marker_rate is None or marker_rate <= 0:
        return fail("marker_sample_rate_invalid")
    expected_duration = expected_interval_count / marker_rate

    def require_equal_int(field: str, expected: int) -> bool:
        for source in (request, post, payload):
            if _strict_int(source.get(field), minimum=0) != expected:
                return False
        return True

    if not require_equal_int("first_sample_index", marker_first):
        return fail("first_sample_index_mismatch")
    if not require_equal_int("last_sample_index", marker_last):
        return fail("last_sample_index_mismatch")
    if not require_equal_int("sample_count", expected_sample_count):
        return fail("sample_count_mismatch")
    if not require_equal_int("interval_count", expected_interval_count):
        return fail("interval_count_mismatch")
    for source_name, source in (("request", request), ("postprocessor", post), ("binding", payload)):
        rate = _finite_float(source.get("sample_rate_hz"), minimum=0.0)
        if rate is None or not math.isclose(rate, marker_rate, rel_tol=0.0, abs_tol=max(1e-12, marker_rate * 1e-12)):
            return fail(f"{source_name}_sample_rate_mismatch")

    one_sample_s = 1.0 / marker_rate
    duration_tolerance_s = one_sample_s + max(1e-12, abs(expected_duration) * 1e-12)
    summary = extract_power_calculation_summary(result_data)
    duration_values = {
        "request": request.get("duration_s"),
        "postprocessor": post.get("duration_s"),
        "binding": payload.get("duration_s"),
        "selected_result": summary.get("active_duration_s"),
    }
    for source_name, value in duration_values.items():
        duration = _finite_float(value, minimum=0.0)
        if duration is None or abs(duration - expected_duration) > duration_tolerance_s:
            return fail(
                f"{source_name}_duration_mismatch",
                expected_duration_s=expected_duration,
                duration_tolerance_s=duration_tolerance_s,
                observed_duration_s=duration,
            )

    marker_drops = _strict_int(stream.get("dropped_samples"), minimum=0)
    request_drops = _strict_int(request.get("dropped_samples"), minimum=0)
    post_drops = _strict_int(post.get("dropped_samples", post.get("drop_count")), minimum=0)
    binding_drops = _strict_int(payload.get("dropped_samples", payload.get("drop_count")), minimum=0)
    if None in {marker_drops, request_drops, post_drops, binding_drops}:
        return fail("dropped_samples_missing")
    if len({marker_drops, request_drops, post_drops, binding_drops}) != 1:
        return fail("dropped_samples_mismatch")
    if marker_drops != 0:
        return fail("dropped_samples_in_command_window", dropped_samples=marker_drops)
    if any(source.get("trace_covers_window") is not True for source in (stream, request, post, payload)):
        return fail("trace_does_not_cover_command_window")

    marker_uncertainty = _boundary_uncertainty_samples(stream.get("boundary_uncertainty_samples"))
    request_uncertainty = _boundary_uncertainty_samples(request.get("boundary_uncertainty_samples"))
    post_uncertainty = _boundary_uncertainty_samples(post.get("boundary_uncertainty_samples"))
    binding_uncertainty = _boundary_uncertainty_samples(payload.get("boundary_uncertainty_samples"))
    maximum_uncertainty = _finite_float(request.get("maximum_boundary_uncertainty_samples"), minimum=0.0)
    if None in {marker_uncertainty, request_uncertainty, post_uncertainty, binding_uncertainty, maximum_uncertainty}:
        return fail("boundary_uncertainty_missing")
    uncertainty_values = [float(marker_uncertainty), float(request_uncertainty), float(post_uncertainty), float(binding_uncertainty)]
    if max(uncertainty_values) != min(uncertainty_values):
        return fail("boundary_uncertainty_mismatch")
    for source_name, source in (("postprocessor", post), ("binding", payload)):
        source_maximum = _strict_int(source.get("maximum_boundary_uncertainty_samples"), minimum=0)
        if source_maximum != maximum_uncertainty:
            return fail(f"{source_name}_maximum_boundary_uncertainty_mismatch")
    if float(marker_uncertainty) > float(maximum_uncertainty):
        return fail(
            "boundary_uncertainty_exceeds_limit",
            boundary_uncertainty_samples=marker_uncertainty,
            maximum_boundary_uncertainty_samples=maximum_uncertainty,
        )

    energy_semantics = str(post.get("energy_semantics") or "").strip().lower()
    if energy_semantics != "calibrated_input_energy_unsubtracted":
        return fail("energy_semantics_not_calibrated_input_energy_unsubtracted")
    if str(payload.get("energy_semantics") or "").strip().lower() != energy_semantics:
        return fail("binding_energy_semantics_mismatch")
    expected_energy_field = f"{summary.get('source_key')}.energy" if summary.get("source_key") else ""
    energy_field = str(post.get("energy_field") or "").strip()
    if not expected_energy_field or energy_field != expected_energy_field:
        return fail("energy_source_field_mismatch", expected_energy_field=expected_energy_field, energy_field=energy_field)
    if str(payload.get("energy_field") or "").strip() != energy_field:
        return fail("binding_energy_source_field_mismatch")
    parsed_energy = _finite_float(summary.get("energy_total_j"), minimum=0.0)
    post_energy = _finite_float(post.get("energy_j"), minimum=0.0)
    binding_energy = _finite_float(payload.get("energy_j"), minimum=0.0)
    if None in {parsed_energy, post_energy, binding_energy}:
        return fail("calibrated_input_energy_value_missing")
    energy_tolerance_j = max(1e-9, abs(float(parsed_energy)) * 1e-9)
    if abs(float(post_energy) - float(parsed_energy)) > energy_tolerance_j or abs(float(binding_energy) - float(parsed_energy)) > energy_tolerance_j:
        return fail("calibrated_input_energy_value_mismatch")

    result.update({
        "verified": True,
        "raw_input_energy_verified": True,
        "calibrated_input_energy_unsubtracted_verified": True,
        "status": "verified",
        "run_id": run_id,
        "window_id": window_id,
        "source": "fast_firmware",
        "first_sample_index": marker_first,
        "last_sample_index": marker_last,
        "sample_count": expected_sample_count,
        "interval_count": expected_interval_count,
        "sample_rate_hz": marker_rate,
        "integrated_duration_s": expected_duration,
        "duration_tolerance_s": duration_tolerance_s,
        "dropped_samples": 0,
        "boundary_uncertainty_samples": marker_uncertainty,
        "maximum_boundary_uncertainty_samples": maximum_uncertainty,
        "energy_semantics": energy_semantics,
        "energy_field": energy_field,
        "expected_energy_field": expected_energy_field,
        "calibrated_input_energy_unsubtracted_j": parsed_energy,
        # Compatibility alias consumed by existing report generation.
        "raw_input_energy_j": parsed_energy,
        "parsed_energy_total_j": parsed_energy,
        "energy_tolerance_j": energy_tolerance_j,
    })
    return result


def _command_window_binding(
    run_dir: Path,
    result_data: Mapping[str, Any],
    timing: Mapping[str, Any],
    result_path: Path | None = None,
) -> dict[str, Any]:
    """Validate an explicit trace-to-command integration-window binding.

    A similar duration is useful diagnostics, but cannot prove that the energy
    numerator covers the command that emitted the completed-work denominator.
    The postprocessor therefore has to emit a binding manifest containing the
    trace hash and both intervals.  The collector verifies that manifest and the
    captured command timestamps before allowing a command-window claim.
    """
    manifest_path: Path | None = None
    payload: Mapping[str, Any] | None = None
    for candidate in (
        run_dir / "command_window_binding.json",
        run_dir / "processed" / "command_window_binding.json",
        run_dir / "processed_complete_window" / "command_window_binding.json",
    ):
        if candidate.is_file():
            try:
                loaded = json.loads(candidate.read_text(encoding="utf-8"))
            except Exception:
                loaded = None
            if isinstance(loaded, Mapping):
                payload = loaded
                manifest_path = candidate
                break
    if payload is None:
        payload = _find_mapping(
            result_data,
            {"command_window_trace_binding", "command_window_binding", "trace_command_binding"},
        )
    result: dict[str, Any] = {
        "verified": False,
        "raw_input_energy_verified": False,
        "status": "missing",
        "manifest_path": str(manifest_path or ""),
        "binding_method": "",
    }
    if not isinstance(payload, Mapping):
        return result
    method = str(payload.get("binding_method") or payload.get("method") or "").strip()
    result["binding_method"] = method
    if payload.get("schema") == _COMMAND_WINDOW_BINDING_SCHEMA_V2 or method == _COMMAND_WINDOW_BINDING_METHOD_V2:
        return _command_window_binding_v2(
            payload,
            manifest_path=manifest_path,
            result_data=result_data,
            timing=timing,
            result_path=result_path,
        )
    allowed_methods = {"trace_timestamp_crop", "collector_command_marker_crop"}
    if method not in allowed_methods:
        result["status"] = "unsupported_binding_method"
        return result

    trace_text = str(payload.get("trace_path") or payload.get("raw_trace_path") or "").strip()
    declared_trace_sha = str(payload.get("trace_sha256") or payload.get("raw_trace_sha256") or "").strip().lower()
    if not trace_text or re.fullmatch(r"[0-9a-f]{64}", declared_trace_sha) is None:
        result["status"] = "trace_path_or_sha256_missing"
        return result
    trace_path = Path(trace_text).expanduser()
    if not trace_path.is_absolute():
        trace_path = (manifest_path.parent if manifest_path is not None else run_dir) / trace_path
    if not trace_path.is_file():
        result["status"] = "trace_file_missing"
        result["trace_path"] = str(trace_path)
        return result
    try:
        actual_trace_sha = _sha256_path(trace_path)
    except Exception as exc:
        result["status"] = "trace_read_failed"
        result["error"] = f"{type(exc).__name__}: {exc}"
        return result
    result["trace_path"] = str(trace_path.resolve())
    result["trace_sha256"] = actual_trace_sha
    if actual_trace_sha != declared_trace_sha:
        result["status"] = "trace_sha256_mismatch"
        return result

    result_text = str(payload.get("result_path") or payload.get("power_result_path") or "").strip()
    declared_result_sha = str(payload.get("result_sha256") or payload.get("power_result_sha256") or "").strip().lower()
    energy_semantics = str(payload.get("energy_semantics") or "").strip().lower()
    energy_field = str(payload.get("energy_field") or "").strip()
    raw_energy = payload.get("raw_input_energy_j")
    if not result_text or re.fullmatch(r"[0-9a-f]{64}", declared_result_sha) is None:
        result["status"] = "result_path_or_sha256_missing"
        return result
    bound_result_path = Path(result_text).expanduser()
    if not bound_result_path.is_absolute():
        bound_result_path = (manifest_path.parent if manifest_path is not None else run_dir) / bound_result_path
    if not bound_result_path.is_file():
        result["status"] = "bound_result_file_missing"
        result["bound_result_path"] = str(bound_result_path)
        return result
    if result_path is not None:
        try:
            if bound_result_path.resolve() != Path(result_path).resolve():
                result["status"] = "bound_result_is_not_selected_result"
                return result
        except Exception:
            result["status"] = "bound_result_path_compare_failed"
            return result
    try:
        actual_result_sha = _sha256_path(bound_result_path)
    except Exception as exc:
        result["status"] = "bound_result_read_failed"
        result["error"] = f"{type(exc).__name__}: {exc}"
        return result
    result["bound_result_path"] = str(bound_result_path.resolve())
    result["bound_result_sha256"] = actual_result_sha
    if actual_result_sha != declared_result_sha:
        result["status"] = "bound_result_sha256_mismatch"
        return result
    summary = extract_power_calculation_summary(result_data)
    source_key = str(summary.get("source_key") or "")
    expected_energy_field = f"{source_key}.energy" if source_key else ""
    try:
        raw_energy_j = float(raw_energy)
        parsed_energy_j = float(summary.get("energy_total_j"))
    except Exception:
        result["status"] = "raw_input_energy_value_missing"
        return result
    energy_tolerance_j = max(1e-9, abs(parsed_energy_j) * 1e-9)
    result.update({
        "energy_semantics": energy_semantics,
        "energy_field": energy_field,
        "expected_energy_field": expected_energy_field,
        "raw_input_energy_j": raw_energy_j,
        "parsed_energy_total_j": parsed_energy_j,
        "raw_input_energy_delta_j": abs(raw_energy_j - parsed_energy_j),
        "raw_input_energy_tolerance_j": energy_tolerance_j,
    })
    if energy_semantics != "raw_input_energy":
        result["status"] = "energy_semantics_not_raw_input_energy"
        return result
    if not expected_energy_field or energy_field != expected_energy_field:
        result["status"] = "energy_source_field_mismatch"
        return result
    if not math.isfinite(raw_energy_j) or raw_energy_j < 0 or abs(raw_energy_j - parsed_energy_j) > energy_tolerance_j:
        result["status"] = "raw_input_energy_value_mismatch"
        return result

    def _integer(*names: str) -> int | None:
        for name in names:
            try:
                value = int(payload.get(name))
            except Exception:
                continue
            if value > 0:
                return value
        return None

    command_start = _integer("command_start_ns", "workload_start_ns")
    command_end = _integer("command_end_ns", "workload_end_ns")
    integrated_start = _integer("integrated_start_ns", "energy_window_start_ns")
    integrated_end = _integer("integrated_end_ns", "energy_window_end_ns")
    captured_start = _positive_int(timing.get("start_ns"))
    captured_end = _positive_int(timing.get("end_ns"))
    if "alignment_tolerance_ns" not in payload:
        result["status"] = "alignment_tolerance_ns_missing"
        return result
    tolerance_ns = _strict_int(payload.get("alignment_tolerance_ns"), minimum=0)
    if tolerance_ns is None:
        result["status"] = "alignment_tolerance_ns_invalid"
        return result
    result.update({
        "command_start_ns": command_start,
        "command_end_ns": command_end,
        "integrated_start_ns": integrated_start,
        "integrated_end_ns": integrated_end,
        "captured_command_start_ns": captured_start,
        "captured_command_end_ns": captured_end,
        "alignment_tolerance_ns": tolerance_ns,
    })
    if None in {command_start, command_end, integrated_start, integrated_end, captured_start, captured_end}:
        result["status"] = "binding_timestamps_missing"
        return result
    if not (command_start < command_end and integrated_start < integrated_end):
        result["status"] = "binding_interval_invalid"
        return result
    deltas = {
        "captured_start_delta_ns": abs(int(command_start) - int(captured_start)),
        "captured_end_delta_ns": abs(int(command_end) - int(captured_end)),
        "integrated_start_delta_ns": abs(int(integrated_start) - int(command_start)),
        "integrated_end_delta_ns": abs(int(integrated_end) - int(command_end)),
    }
    result.update(deltas)
    if any(delta > tolerance_ns for delta in deltas.values()):
        result["status"] = "trace_command_interval_mismatch"
        return result
    result["verified"] = True
    result["raw_input_energy_verified"] = True
    result["status"] = "verified"
    return result


