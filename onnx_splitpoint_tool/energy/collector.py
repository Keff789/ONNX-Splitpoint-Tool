HOST_NORMALIZATION_ROLE_NONE = "none"
HOST_NORMALIZATION_ROLE_TENSORRT_FULL = "tensorrt_full"
_HOST_NORMALIZATION_ROLES = frozenset(
    {HOST_NORMALIZATION_ROLE_NONE, HOST_NORMALIZATION_ROLE_TENSORRT_FULL}
)
_TENSORRT_FULL_ENERGY_RUN_IDS = frozenset(
    {
        "native_full_tensorrt",
        "ort_tensorrt",
        "tensorrt",
        "tensorrt_full",
        "trt_full",
    }
)


def normalize_host_normalization_role(value: Any) -> str:
    """Return one exact accelerator-idle correction role or fail closed.

    Existing callers do not request host normalization, so ``None`` and the
    empty string deliberately resolve to ``none``.  Non-empty unknown values
    are rejected instead of being guessed from a backend substring.
    """

    if value is None or str(value).strip() == "":
        return HOST_NORMALIZATION_ROLE_NONE
    role = str(value).strip().lower()
    if role not in _HOST_NORMALIZATION_ROLES:
        raise ValueError(
            "Unsupported host_normalization_role "
            f"{value!r}; expected one of {sorted(_HOST_NORMALIZATION_ROLES)}"
        )
    return role


def select_host_normalization_role(
    *, run_id: Any, target_variant: Any
) -> str:
    """Select TensorRT-Full correction from an exact row identity.

    A TensorRT-containing split is intentionally *not* enough.  Both the
    canonical run identity and the measured ``full`` target variant must match.
    Unknown/missing identities return ``none`` so callers cannot accidentally
    subtract M.2 idle power from Hailo, DeepX, split, or calibration captures.
    """

    rid = str(run_id or "").strip().lower()
    variant = str(target_variant or "").strip().lower()
    if variant == "full" and rid in _TENSORRT_FULL_ENERGY_RUN_IDS:
        return HOST_NORMALIZATION_ROLE_TENSORRT_FULL
    return HOST_NORMALIZATION_ROLE_NONE


def apply_full_system_current_scale(
    summary: Mapping[str, Any],
    *,
    physical_scope: Any,
    scale_factor: Any,
    calibrated_at: Any = "",
    calibration_evidence: Any = "",
    calibration_sha256: Any = "",
    setup_id: Any = "",
    accelerator: Any = "",
    urecs_address: Any = "",
    data_port: Any = None,
) -> dict[str, Any]:
    """Verify and apply one setup-bound Full-System DC gain trim.

    This compatibility entry point intentionally no longer trusts a bare
    numeric factor.  The configured value must be backed by the immutable
    calibration evidence and SHA-256 generated by the guided GUI workflow.
    Normal collection uses the already-verified result passed to
    :func:`apply_configured_energy_baselines`.
    """

    setup_view = {
        "setup_id": str(setup_id or ""),
        "accelerator": str(accelerator or ""),
        "urecs_address": str(urecs_address or ""),
        "data_port": data_port,
        "full_system_current_scale_factor": scale_factor,
        "full_system_current_scale_calibrated_at": str(calibrated_at or ""),
        "full_system_current_scale_calibration_evidence": str(
            calibration_evidence or ""
        ),
        "full_system_current_scale_calibration_sha256": str(
            calibration_sha256 or ""
        ),
    }
    verification = verify_full_system_current_scale_calibration(
        setup_view,
        physical_scope=physical_scope,
    )
    return apply_verified_full_system_current_scale(
        summary,
        physical_scope=physical_scope,
        verification=verification,
    )


def apply_configured_energy_baselines(
    summary: Mapping[str, Any],
    *,
    idle_baseline_w: float | None,
    accelerator_idle_w: float | None,
    host_normalization_role: Any = None,
    accelerator_idle_calibration: Mapping[str, Any] | None = None,
    host_normalization_source_run_id: Any = None,
    host_normalization_target_variant: Any = None,
    physical_scope: Any = "",
    full_system_current_scale_factor: Any = None,
    full_system_current_scale_calibrated_at: Any = "",
    full_system_current_scale_calibration_evidence: Any = "",
    full_system_current_scale_calibration_sha256: Any = "",
    full_system_current_scale_verification: Mapping[str, Any] | None = None,
    setup_id: Any = "",
    accelerator: Any = "",
    urecs_address: Any = "",
    data_port: Any = None,
) -> dict[str, Any]:
    """Apply the verified FS board trim, then calibrated baseline values.

    ``idle_baseline_w`` and ``accelerator_idle_w`` are stored in the same
    post-scale domain as normal Full-System results.  Saving a new FS gain trim
    invalidates older baseline values, and the M.2 idle routine measures again
    through the verified trim.  Scaling the stored baselines a second time
    would therefore be wrong.
    """

    if full_system_current_scale_verification is None:
        setup_view = {
            "setup_id": str(setup_id or ""),
            "accelerator": str(accelerator or ""),
            "urecs_address": str(urecs_address or ""),
            "data_port": data_port,
            "full_system_current_scale_factor": full_system_current_scale_factor,
            "full_system_current_scale_calibrated_at": str(
                full_system_current_scale_calibrated_at or ""
            ),
            "full_system_current_scale_calibration_evidence": str(
                full_system_current_scale_calibration_evidence or ""
            ),
            "full_system_current_scale_calibration_sha256": str(
                full_system_current_scale_calibration_sha256 or ""
            ),
        }
        verification = verify_full_system_current_scale_calibration(
            setup_view,
            physical_scope=physical_scope,
        )
    else:
        verification = dict(full_system_current_scale_verification)
    scaled_summary = apply_verified_full_system_current_scale(
        summary,
        physical_scope=physical_scope,
        verification=verification,
    )

    role = normalize_host_normalization_role(host_normalization_role)
    requested = role == HOST_NORMALIZATION_ROLE_TENSORRT_FULL
    source_run_id = str(host_normalization_source_run_id or "").strip().lower()
    target_variant = str(host_normalization_target_variant or "").strip().lower()
    identity_verified = bool(
        requested
        and select_host_normalization_role(
            run_id=source_run_id, target_variant=target_variant
        ) == HOST_NORMALIZATION_ROLE_TENSORRT_FULL
    )
    calibration = dict(accelerator_idle_calibration or {})
    calibration_verified = bool(
        calibration.get("accelerator_idle_calibration_verified") is True
        and str(calibration.get("accelerator_idle_calibration_status") or "")
        == "verified"
    )
    usable_accelerator_idle_w: float | None = None
    accelerator_idle_invalid = False
    if accelerator_idle_w is not None:
        try:
            candidate = float(accelerator_idle_w)
        except (TypeError, ValueError):
            accelerator_idle_invalid = True
        else:
            if (
                isinstance(accelerator_idle_w, bool)
                or not math.isfinite(candidate)
                or candidate < 0.0
            ):
                accelerator_idle_invalid = True
            else:
                usable_accelerator_idle_w = candidate
    correction_authorized = bool(
        requested and identity_verified and calibration_verified
    )
    out = apply_energy_baselines(
        scaled_summary,
        idle_baseline_w=idle_baseline_w,
        accelerator_idle_w=(
            usable_accelerator_idle_w if correction_authorized else None
        ),
        host_only=correction_authorized,
    )
    applied = bool(
        correction_authorized
        and usable_accelerator_idle_w is not None
        and isinstance(out.get("host_normalized_energy_est_j"), (int, float))
    )
    out.update(
        {
            "host_normalization_role": role,
            "host_normalization_source_run_id": source_run_id,
            "host_normalization_target_variant": target_variant,
            "host_normalization_identity_verified": identity_verified,
            "accelerator_idle_correction_requested": requested,
            "accelerator_idle_correction_applied": applied,
            "accelerator_idle_correction_status": (
                "applied"
                if applied
                else "unavailable_identity_unverified"
                if requested and not identity_verified
                else "unavailable_invalid_accelerator_idle_w"
                if requested and accelerator_idle_invalid
                else "unavailable_missing_accelerator_idle_w"
                if requested and accelerator_idle_w is None
                else "unavailable_calibration_binding_unverified"
                if requested and not calibration_verified
                else "unavailable_energy_or_duration"
                if requested
                else "not_requested"
            ),
            "energy_baseline_domain": "post_full_system_scale",
        }
    )
    out.update(calibration)
    out["accelerator_idle_w_applied"] = (
        usable_accelerator_idle_w if applied else None
    )
    return out


_POWER_CALC_SEMAPHORES: dict[int, threading.Semaphore] = {}
_POWER_CALC_SEMAPHORES_LOCK = threading.Lock()

def _powercalc_semaphore() -> threading.Semaphore | None:
    """Limit concurrent power_calculations processes in parallel setup runs.

    Each u.RECS gets its own collector and storage path, so acquisition can run
    in parallel.  Postprocessing is CPU/I/O-heavy on the tool host, therefore
    the default serializes power_calculations.  Set
    ONNX_SPLITPOINT_POWER_CALC_WORKERS=0 to disable the limiter.
    """
    try:
        from onnx_splitpoint_tool.process_control import workflow_resource_options
        limit = int(workflow_resource_options().get("powercalc_workers", os.environ.get("ONNX_SPLITPOINT_POWER_CALC_WORKERS", "1")) or 1)
    except Exception:
        limit = 1
    if limit <= 0:
        return None
    with _POWER_CALC_SEMAPHORES_LOCK:
        sem = _POWER_CALC_SEMAPHORES.get(limit)
        if sem is None:
            sem = threading.Semaphore(limit)
            _POWER_CALC_SEMAPHORES[limit] = sem
        return sem

def _cancel_requested(cancel_event: Any = None) -> bool:
    return bool(
        cancel_event is not None
        and getattr(cancel_event, "is_set", lambda: False)()
    )


def _terminate_process_group(proc: subprocess.Popen, *, grace_s: float = 2.0) -> None:
    """Terminate a command and every child it started.

    u.RECS launches the measured workload as a child process.  Terminating only
    the collector PID can therefore leave an SSH benchmark running after the
    GUI reports cancellation.  Every long-running energy command is started in
    a fresh session below, so POSIX process-group termination is both bounded
    and scoped to this one measurement window.
    """
    terminate_process_tree(proc, grace_s=grace_s)


@budget_controller_work("postcalc")
def _run_powercalc_limited(
    cmd: list[str],
    *,
    cwd: Path | None,
    stdout_path: Path,
    stderr_path: Path,
    timeout: float | None = None,
    cancel_event: Any = None,
) -> dict[str, Any]:
    sem = _powercalc_semaphore()
    acquired = False
    try:
        if sem is not None:
            while not acquired:
                if _cancel_requested(cancel_event):
                    return {
                        "cmd": cmd,
                        "rc": 130,
                        "stdout": "",
                        "stderr": "cancelled while waiting for power-calculation slot",
                        "duration_s": 0.0,
                        "cancelled": True,
                    }
                acquired = bool(sem.acquire(timeout=0.25))
        return _run_one(
            cmd,
            cwd=cwd,
            stdout_path=stdout_path,
            stderr_path=stderr_path,
            timeout=timeout,
            cancel_event=cancel_event,
        )
    finally:
        if sem is not None and acquired:
            try:
                sem.release()
            except Exception:
                pass


