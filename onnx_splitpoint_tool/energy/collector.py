def _sha256_text(value: str) -> str:
    return hashlib.sha256(str(value).encode("utf-8")).hexdigest()


def _render_energy_preflight_template(
    template: str,
    *,
    nonce: str,
    repeat_index: int | str,
    attestation_path: str | Path,
) -> str:
    """Bind a preflight/workload command to one measurement repeat.

    Deliberately use improbable literal tokens instead of ``str.format`` so
    shell/JSON braces in an archived command are never interpreted.  Values are
    shell quoted because callers normally place the tokens as CLI arguments.
    """
    return (
        str(template)
        .replace(_ENERGY_PREFLIGHT_NONCE_TOKEN, shlex.quote(str(nonce)))
        .replace(_ENERGY_PREFLIGHT_REPEAT_TOKEN, shlex.quote(str(repeat_index)))
        .replace(_ENERGY_PREFLIGHT_ATTESTATION_TOKEN, shlex.quote(str(attestation_path)))
    )


def _preflight_attestation_from_stdout(stdout_path: Path) -> tuple[dict[str, Any] | None, str]:
    try:
        raw = stdout_path.read_text(encoding="utf-8", errors="replace").strip()
    except Exception as exc:
        return None, f"preflight_stdout_unreadable:{type(exc).__name__}"
    if not raw:
        return None, "preflight_attestation_missing"
    marker_payloads = [
        line.split(_ENERGY_PREFLIGHT_STDOUT_MARKER, 1)[1].strip()
        for line in raw.splitlines()
        if _ENERGY_PREFLIGHT_STDOUT_MARKER in line
    ]
    candidates = list(reversed(marker_payloads))
    candidates.append(raw)
    for candidate in candidates:
        try:
            value = json.loads(candidate)
        except Exception:
            continue
        if isinstance(value, Mapping):
            return dict(value), ""
    return None, "preflight_attestation_json_invalid"


def _preflight_attestation_seal(payload: Mapping[str, Any]) -> str:
    unsigned = dict(payload)
    unsigned.pop("attestation_sha256", None)
    canonical = json.dumps(
        unsigned,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    ).encode("utf-8")
    return hashlib.sha256(canonical).hexdigest()


def _validate_energy_preflight_attestation(
    payload: Mapping[str, Any] | None,
    *,
    nonce: str,
    started_at_unix_ns: int,
    ended_at_unix_ns: int,
    max_age_s: float,
    expected_command_contract_sha256: str,
) -> dict[str, Any]:
    reasons: list[str] = []
    data = dict(payload or {})
    if not data:
        reasons.append("preflight_attestation_missing")
    if str(data.get("schema") or "") != _ENERGY_PREFLIGHT_ATTESTATION_SCHEMA_V1:
        reasons.append("preflight_attestation_schema_mismatch")
    if _strict_int(data.get("schema_version"), minimum=1) != 1:
        reasons.append("preflight_attestation_schema_version_mismatch")
    if data.get("ok") is not True:
        reasons.append("preflight_attestation_not_ok")
    if str(data.get("artifact_verification_status") or "").strip().lower() != "pass":
        reasons.append("preflight_artifact_verification_not_pass")
    if not secrets.compare_digest(str(data.get("nonce") or ""), str(nonce)):
        reasons.append("preflight_attestation_nonce_mismatch")

    command_contract_sha256 = str(data.get("command_contract_sha256") or "").strip().lower()
    if re.fullmatch(r"[0-9a-f]{64}", command_contract_sha256) is None:
        reasons.append("preflight_command_contract_sha256_invalid")
    elif not secrets.compare_digest(
        command_contract_sha256, expected_command_contract_sha256
    ):
        reasons.append("preflight_command_contract_sha256_mismatch")

    expected_seal = _preflight_attestation_seal(data) if data else ""
    actual_seal = str(data.get("attestation_sha256") or "").strip().lower()
    if re.fullmatch(r"[0-9a-f]{64}", actual_seal) is None:
        reasons.append("preflight_attestation_seal_missing_or_invalid")
    elif not secrets.compare_digest(actual_seal, expected_seal):
        reasons.append("preflight_attestation_seal_mismatch")

    created_at = _strict_int(data.get("created_at_unix_ns"), minimum=1)
    expires_at = _strict_int(data.get("expires_at_unix_ns"), minimum=1)
    max_age_ns = max(1, int(float(max_age_s) * 1_000_000_000))
    # A fresh, unpredictable nonce is the primary freshness binding.  The five
    # second allowance only absorbs ordinary NTP/serialization skew; it cannot
    # make a stale attestation pass because the nonce must also match.
    clock_allowance_ns = min(5_000_000_000, max_age_ns)
    if created_at is None or expires_at is None:
        reasons.append("preflight_attestation_timestamps_missing")
    else:
        if created_at < int(started_at_unix_ns) - clock_allowance_ns:
            reasons.append("preflight_attestation_not_fresh")
        if created_at > int(ended_at_unix_ns) + clock_allowance_ns:
            reasons.append("preflight_attestation_created_in_future")
        if expires_at <= int(ended_at_unix_ns):
            reasons.append("preflight_attestation_expired")
        if expires_at <= created_at or expires_at - created_at > max_age_ns:
            reasons.append("preflight_attestation_validity_window_invalid")
        if int(ended_at_unix_ns) - created_at > max_age_ns:
            reasons.append("preflight_attestation_too_old")
    return {
        "ok": not reasons,
        "status": "verified" if not reasons else "failed",
        "reasons": reasons,
        "schema": str(data.get("schema") or ""),
        "schema_version": data.get("schema_version"),
        "command_contract_sha256": command_contract_sha256,
        "expected_command_contract_sha256": expected_command_contract_sha256,
        "created_at_unix_ns": created_at,
        "expires_at_unix_ns": expires_at,
        "attestation_sha256": actual_seal,
        "expected_attestation_sha256": expected_seal,
        "max_age_s": float(max_age_s),
    }


def _run_energy_preflight(
    command_template: str,
    *,
    workload_command_template: str,
    evidence_dir: Path,
    repeat_index: int | str,
    timeout_s: float,
    max_age_s: float,
    expected_command_contract_sha256: str,
    runtime_attestation_path_template: str = "",
    cancel_event: Any = None,
    subprocess_env: Mapping[str, str] | None = None,
) -> tuple[dict[str, Any], str]:
    """Run and validate the expensive workload preflight outside acquisition.

    Returns the evidence record and the nonce-bound workload command.  The
    latter performs only the runner's small attestation read/validation once
    u.RECS starts sampling.
    """
    evidence_dir.mkdir(parents=True, exist_ok=True)
    nonce = secrets.token_hex(32)
    attestation_path = evidence_dir / "preflight_attestation.json"
    runtime_attestation_path = (
        str(runtime_attestation_path_template or attestation_path)
        .replace(_ENERGY_PREFLIGHT_NONCE_TOKEN, nonce)
        .replace(_ENERGY_PREFLIGHT_REPEAT_TOKEN, str(repeat_index))
        .replace(_ENERGY_PREFLIGHT_ATTESTATION_TOKEN, str(attestation_path))
    )
    rendered_preflight = _render_energy_preflight_template(
        command_template,
        nonce=nonce,
        repeat_index=repeat_index,
        attestation_path=runtime_attestation_path,
    )
    rendered_workload = _render_energy_preflight_template(
        workload_command_template,
        nonce=nonce,
        repeat_index=repeat_index,
        attestation_path=runtime_attestation_path,
    )
    command_path = write_command_script(
        evidence_dir / "preflight_command.sh", rendered_preflight
    )
    stdout_path = evidence_dir / "preflight_stdout.log"
    stderr_path = evidence_dir / "preflight_stderr.log"
    started_ns = time.time_ns()
    result = _run_one(
        [str(command_path)],
        cwd=None,
        stdout_path=stdout_path,
        stderr_path=stderr_path,
        timeout=float(timeout_s),
        cancel_event=cancel_event,
        heartbeat_path=evidence_dir / "preflight_status.json",
        heartbeat_context={
            "phase": "energy_preflight",
            "repeat_index": repeat_index,
        },
        subprocess_env=subprocess_env,
    )
    ended_ns = time.time_ns()
    payload, parse_error = _preflight_attestation_from_stdout(stdout_path)
    validation = _validate_energy_preflight_attestation(
        payload,
        nonce=nonce,
        started_at_unix_ns=started_ns,
        ended_at_unix_ns=ended_ns,
        max_age_s=max_age_s,
        expected_command_contract_sha256=expected_command_contract_sha256,
    )
    reasons = list(validation.get("reasons") or [])
    preflight_cancelled = bool(result.get("cancelled"))
    if preflight_cancelled:
        reasons.insert(0, "preflight_cancelled")
    if result.get("rc") != 0:
        reasons.insert(0, "preflight_command_rc_nonzero")
    if parse_error and parse_error not in reasons:
        reasons.append(parse_error)
    validation["reasons"] = list(dict.fromkeys(reasons))
    validation["ok"] = not validation["reasons"]
    validation["status"] = (
        "cancelled" if preflight_cancelled
        else "verified" if validation["ok"]
        else "failed"
    )
    if payload is not None:
        _write_json(attestation_path, payload)
    evidence: dict[str, Any] = {
        "schema": "onnx-splitpoint/energy-preflight-evidence",
        "schema_version": 1,
        "requested": True,
        "ok": bool(validation["ok"]),
        "status": str(validation["status"]),
        "cancelled": preflight_cancelled,
        "repeat_index": repeat_index,
        "nonce": nonce,
        "nonce_sha256": _sha256_text(nonce),
        "command_template_sha256": _sha256_text(command_template),
        "rendered_command_sha256": _sha256_text(rendered_preflight),
        "workload_template_sha256": _sha256_text(workload_command_template),
        "rendered_workload_sha256": _sha256_text(rendered_workload),
        "command_path": str(command_path),
        "command_file_sha256": _sha256_path(command_path),
        "stdout_path": str(stdout_path),
        "stdout_sha256": _sha256_path(stdout_path) if stdout_path.is_file() else "",
        "stderr_path": str(stderr_path),
        "stderr_sha256": _sha256_path(stderr_path) if stderr_path.is_file() else "",
        "attestation_path": str(attestation_path),
        "runtime_attestation_path": runtime_attestation_path,
        "runtime_attestation_path_scope": (
            "caller_supplied_runtime_host"
            if runtime_attestation_path_template else "local_measurement_host"
        ),
        "attestation_file_sha256": (
            _sha256_path(attestation_path) if attestation_path.is_file() else ""
        ),
        "rc": result.get("rc"),
        "duration_s": result.get("duration_s"),
        "started_at_unix_ns": started_ns,
        "ended_at_unix_ns": ended_ns,
        "timeout_s": float(timeout_s),
        "expected_command_contract_sha256": expected_command_contract_sha256,
        "validation": validation,
        "collector_started": False,
    }
    _write_json(evidence_dir / "preflight_evidence.json", evidence)
    return evidence, rendered_workload


def _resolve_artifact_path(raw_path: Any, *, relative_to: Path) -> Path | None:
    text = str(raw_path or "").strip()
    if not text:
        return None
    path = Path(text).expanduser()
    if not path.is_absolute():
        path = relative_to / path
    return path


def _strict_int(value: Any, *, minimum: int | None = None) -> int | None:
    if isinstance(value, bool):
        return None
    try:
        parsed = int(value)
    except Exception:
        return None
    try:
        if float(value) != float(parsed):
            return None
    except Exception:
        return None
    if minimum is not None and parsed < minimum:
        return None
    return parsed


def _finite_float(value: Any, *, minimum: float | None = None) -> float | None:
    if isinstance(value, bool):
        return None
    try:
        parsed = float(value)
    except Exception:
        return None
    if not math.isfinite(parsed):
        return None
    if minimum is not None and parsed < minimum:
        return None
    return parsed


def _boundary_uncertainty_samples(value: Any) -> int | None:
    """Return the conservative boundary uncertainty from scalar or edge values."""
    if isinstance(value, Mapping):
        values = [
            _strict_int(value.get(key), minimum=0)
            for key in ("start", "end", "start_samples", "end_samples", "maximum", "max")
        ]
        available = [item for item in values if item is not None]
        return max(available) if available else None
    return _strict_int(value, minimum=0)


def _maximum_boundary_uncertainty_samples() -> int:
    raw = os.environ.get("ONNX_SPLITPOINT_MAX_BOUNDARY_UNCERTAINTY_SAMPLES", "64")
    parsed = _strict_int(raw, minimum=0)
    return int(parsed if parsed is not None else 64)


