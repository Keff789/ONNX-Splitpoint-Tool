    command = f"bash -lc {shlex.quote('echo splitpoint-energy-test; sleep ' + str(float(sleep_s)))}"
    return run_fast_firmware_measurement(command, out_dir, setup=setup, defaults=defaults, duration_s=float(sleep_s) + 0.2, run_count=1, setup_id=setup_id, run_id="sleep_test")
