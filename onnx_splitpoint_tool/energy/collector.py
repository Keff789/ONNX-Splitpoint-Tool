_ENERGY_PREFLIGHT_NONCE_TOKEN = "__ONNX_SPLITPOINT_PREFLIGHT_NONCE__"
_ENERGY_PREFLIGHT_REPEAT_TOKEN = "__ONNX_SPLITPOINT_PREFLIGHT_REPEAT__"
_ENERGY_PREFLIGHT_ATTESTATION_TOKEN = "__ONNX_SPLITPOINT_PREFLIGHT_ATTESTATION__"
