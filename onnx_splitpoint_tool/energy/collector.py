def _prepare_command_window_request_v2(
    run_dir: Path,
    storage_dir: Path,
    *,
    workload_script: Path,
    captured_command_script: Path,
    timing_path: Path,
    physical_scope: str,
    expected_run_id: str,
    expected_window_id: str,
) -> dict[str, Any]:
    """Build the hash-bound request consumed by a marker-aware postprocessor.

    The request is deliberately created after the collector has closed its raw
    trace, but before ``power_calculations`` is invoked.  A legacy collector that
    emits no marker therefore never receives command-window CLI flags and stays
    screening-only.
    """
    marker_path = _find_command_window_marker(run_dir, storage_dir)
    result: dict[str, Any] = {
        "available": False,
        "eligible_for_postprocessor": False,
        "status": "marker_missing",
        "marker_path": str(marker_path or ""),
        "request_path": "",
    }
    if marker_path is None:
        return result
    marker = _read_json_mapping(marker_path)
    if marker is None:
        result["status"] = "marker_json_invalid"
        return result
    result["available"] = True

    command = marker.get("command") if isinstance(marker.get("command"), Mapping) else {}
    stream = marker.get("stream") if isinstance(marker.get("stream"), Mapping) else {}
    run_id = str(marker.get("run_id") or "").strip()
    window_id = str(marker.get("window_id") or "").strip()
    source = str(stream.get("source") or "").strip().lower()
    first = _strict_int(stream.get("first_sample_index"), minimum=0)
    last = _strict_int(stream.get("last_sample_index"), minimum=0)
    total = _strict_int(stream.get("total_samples"), minimum=1)
    # A claim-bearing configured method uses an exact integer sample rate.
    # Preserve that literal contract in the generated request instead of
    # widening it to an equivalent JSON float.
    sample_rate = _strict_int(stream.get("sample_rate_hz"), minimum=1)
    process_rc = _strict_int(command.get("process_rc"))
    process_pid = _strict_int(command.get("process_id", command.get("pid")), minimum=1)
    process_error = command.get("process_error")
    start_clock_uncertainty_ns = _strict_int(command.get("start_clock_read_uncertainty_ns"), minimum=0)
    end_clock_uncertainty_ns = _strict_int(command.get("end_clock_read_uncertainty_ns"), minimum=0)
    dropped = _strict_int(stream.get("dropped_samples"), minimum=0)
    uncertainty = _boundary_uncertainty_samples(stream.get("boundary_uncertainty_samples"))
    coverage = stream.get("trace_covers_window") is True
    valid_for_final = marker.get("valid_for_final_energy") is True
    trace_path = _resolve_artifact_path(stream.get("trace_path"), relative_to=marker_path.parent)
    marker_argv = command.get("argv") if isinstance(command.get("argv"), list) else []
    marked_command_path = _resolve_artifact_path(
        marker_argv[0] if marker_argv else command.get("text"),
        relative_to=marker_path.parent,
    )
    maximum_uncertainty = _maximum_boundary_uncertainty_samples()
    errors: list[str] = []
    if marker.get("schema") != _COMMAND_WINDOW_MARKER_SCHEMA_V2 or _strict_int(marker.get("schema_version")) != 2:
        errors.append("marker_schema_invalid")
    if not run_id or not window_id:
        errors.append("marker_run_or_window_id_missing")
    if run_id != str(expected_run_id or "").strip() or window_id != str(expected_window_id or "").strip():
        errors.append("marker_run_or_window_id_mismatch")
    if source != "fast_firmware":
        errors.append("marker_source_not_fast_firmware")
    if first is None or last is None or last <= first:
        errors.append("marker_bounds_invalid")
    if total is None or (last is not None and last >= total):
        errors.append("marker_total_samples_invalid")
    if sample_rate is None or sample_rate <= 0:
        errors.append("marker_sample_rate_invalid")
    if process_rc is None:
        errors.append("marker_process_rc_missing")
    elif process_rc != 0:
        errors.append("marker_process_rc_nonzero")
    if process_pid is None:
        errors.append("marker_process_pid_missing")
    if process_error not in (None, ""):
        errors.append("marker_process_error_present")
    if start_clock_uncertainty_ns is None or end_clock_uncertainty_ns is None:
        errors.append("marker_clock_read_uncertainty_missing")
    if dropped is None:
        errors.append("marker_dropped_samples_missing")
    elif dropped != 0:
        errors.append("marker_dropped_samples_nonzero")
    if uncertainty is None:
        errors.append("marker_boundary_uncertainty_missing")
    elif uncertainty > maximum_uncertainty:
        errors.append("marker_boundary_uncertainty_exceeds_limit")
    if not coverage:
        errors.append("marker_trace_does_not_cover_window")
    if not valid_for_final:
        errors.append("marker_not_valid_for_final_energy")
    if trace_path is None or not trace_path.is_file():
        errors.append("marker_trace_missing")
    if marked_command_path is None or not marked_command_path.is_file():
        errors.append("marker_command_missing")
    elif marked_command_path.resolve() != captured_command_script.resolve():
        errors.append("marker_command_is_not_captured_command")
    if not captured_command_script.is_file():
        errors.append("captured_command_missing")
    if not workload_script.is_file():
        errors.append("workload_command_missing")
    if not timing_path.is_file():
        errors.append("workload_timing_missing")
    if errors:
        result.update({"status": "marker_contract_invalid", "errors": errors})
        _write_json(run_dir / "command_window_request_rejection.json", result)
        return result

    assert first is not None and last is not None and sample_rate is not None
    assert total is not None and process_rc is not None and dropped is not None
    assert uncertainty is not None and trace_path is not None and marked_command_path is not None
    interval_count = last - first
    sample_count = interval_count + 1
    # Physical scope is recorded independently by the measurement campaign.
    # The numerator semantics describe processing state: calibrated input
    # energy before any idle-baseline subtraction.
    semantics = "calibrated_input_energy_unsubtracted"
    request_path = run_dir / "command_window_request.json"
    request = {
        "schema": _COMMAND_WINDOW_REQUEST_SCHEMA_V2,
        "schema_version": 2,
        "binding_method": _COMMAND_WINDOW_BINDING_METHOD_V2,
        "run_id": run_id,
        "window_id": window_id,
        "source": source,
        "marker_path": str(marker_path.resolve()),
        "marker_sha256": _sha256_path(marker_path),
        "trace_path": str(trace_path.resolve()),
        "trace_sha256": _sha256_path(trace_path),
        "command_path": str(marked_command_path.resolve()),
        "command_sha256": _sha256_path(marked_command_path),
        "workload_command_path": str(workload_script.resolve()),
        "workload_command_sha256": _sha256_path(workload_script),
        "timing_path": str(timing_path.resolve()),
        "timing_sha256": _sha256_path(timing_path),
        "first_sample_index": first,
        "last_sample_index": last,
        "sample_count": sample_count,
        "interval_count": interval_count,
        "sample_rate_hz": sample_rate,
        "duration_s": interval_count / sample_rate,
        "process_rc": process_rc,
        "process_id": process_pid,
        "process_error": process_error,
        "start_clock_read_uncertainty_ns": start_clock_uncertainty_ns,
        "end_clock_read_uncertainty_ns": end_clock_uncertainty_ns,
        "command_start_realtime_ns": command.get("start_realtime_ns"),
        "command_end_realtime_ns": command.get("end_realtime_ns"),
        "command_start_monotonic_ns": command.get("start_monotonic_ns"),
        "command_end_monotonic_ns": command.get("end_monotonic_ns"),
        "dropped_samples": dropped,
        "boundary_uncertainty_samples": uncertainty,
        "maximum_boundary_uncertainty_samples": maximum_uncertainty,
        "trace_covers_window": coverage,
        "valid_for_final_energy": valid_for_final,
        "total_samples": total,
        "index_semantics": "zero_based_inclusive_rows",
        "energy_semantics": semantics,
        "energy_field": "firmware_results.energy",
        "created_at_unix_ns": time.time_ns(),
    }
    _write_json(request_path, request)
    result.update({
        "eligible_for_postprocessor": True,
        "status": "request_ready",
        "request_path": str(request_path),
        "request_sha256": _sha256_path(request_path),
        "request": request,
    })
    return result


