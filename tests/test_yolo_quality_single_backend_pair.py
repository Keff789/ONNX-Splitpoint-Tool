"""Read actual saved software runs; no SDK, inference or remote execution.

Set GENERIC_COMPLETION_SINGLE_BACKEND_FIXTURE to the bound JSON emitted by the
connected three-starter integration. No measurements are generated by this file.
"""
import copy
import json
import os
import shutil
from pathlib import Path

import pytest

from onnx_splitpoint_tool.generic_completion_reporting import completion_pair, validate_completion_case


@pytest.fixture(scope='module')
def saved_cases():
    path = os.environ.get('GENERIC_COMPLETION_SINGLE_BACKEND_FIXTURE')
    if not path:
        pytest.skip('requires preserved connected three-starter software artifacts')
    return json.loads(Path(path).read_text())['rows']


def observed(case):
    path = Path(case['result_path'])
    value = validate_completion_case(json.loads(path.read_text()), case, result_root=path.parent)
    value['result_path'] = str(path)
    assert value['status'] == 'completed'
    return value


@pytest.mark.parametrize('index', range(3))
def test_one_native_backend_actual_completed_pair_without_crossbackend_claim(saved_cases, index):
    case = copy.deepcopy(saved_cases[index]); before = copy.deepcopy(case)
    observation = observed(case)
    pair = completion_pair(observation, case)
    assert pair['eligible_for_technical_transfer'], pair['native_generic_completed_endpoint_evidence']
    assert pair['native_generic_completed_endpoint_evidence']['status'] == 'verified'
    assert pair['native_cross_backend_output_endpoint_match'] is False
    callback_observation = dict(observation)
    callback_observation.pop('result_path')
    assert completion_pair(callback_observation, case)['eligible_for_technical_transfer']
    assert pair['quality_transfer_eligibility_checks']['native_output_endpoint_match'] is False
    assert pair['claim_transfer_eligibility_checks']['native_output_endpoint_match'] is False
    assert not pair['eligible_for_quality_transfer'] and not pair['eligible_for_claim_transfer']
    assert case == before
    native = json.loads(Path(case['original_run']).joinpath('reports/native_producer_combined_summary.json').read_text())
    assert all(row['output_endpoint_match'] is False and row['performance_claim_eligible'] is False
               for row in native['rows'])


@pytest.mark.parametrize('mutation', [
    'endpoint', 'primitive', 'native_command_sha', 'selected_binding_sha', 'original_run',
    'runtime_original_run', 'native_counts', 'native_times', 'input_contract', 'reference_sha',
    'output_manifest_sha', 'request_path', 'observation_fps', 'observation_count', 'backend_identity',
])
def test_saved_pair_drift_remains_ineligible(saved_cases, mutation):
    case = copy.deepcopy(saved_cases[0]); observation = observed(case)
    if mutation == 'endpoint':
        case['runtime_config']['identity']['output_endpoint_id'] = 'detection:decoded_pre_nms:' + '0'*64
    elif mutation == 'primitive':
        case['completion_contract']['processor_contract']['unexpected_semantic_change'] = True
    elif mutation == 'native_command_sha':
        case['native_command_contract_sha256'] = '0'*64
    elif mutation == 'selected_binding_sha':
        case['native_quality_binding_sha256'] = '0'*64
    elif mutation == 'original_run':
        case['original_run'] += '-foreign'
    elif mutation == 'runtime_original_run':
        case['runtime_config']['original_run'] += '-foreign'
    elif mutation == 'native_counts':
        case['native_measurement_boundary']['observed_completed_counts'][0] = 999
    elif mutation == 'native_times':
        case['native_measurement_boundary']['observed_measurement_times_s'][0] += 1
    elif mutation == 'input_contract':
        case['input_binding']['prepared_input_contract']['source_image_sha256'] = '0'*64
    elif mutation == 'reference_sha':
        case['runtime_config']['functional_reference']['input_sha256'] = '0'*64
    elif mutation == 'output_manifest_sha':
        case['runtime_config']['functional_reference']['source_manifest_sha256'] = '0'*64
    elif mutation == 'request_path':
        case['generic_original_quality_request'] = case['native_source']
    elif mutation == 'observation_fps':
        observation['completed_task_fps'] *= 2
    elif mutation == 'observation_count':
        observation['completed_task_count'] -= 1
    elif mutation == 'backend_identity':
        case['runtime_config']['identity'].update(direction='deepx_to_trt', comparison_backend='deepx')
    pair = completion_pair(observation, case)
    assert not pair['eligible_for_technical_transfer']
    assert pair['native_generic_completed_endpoint_evidence']['status'] == 'unverified'
    assert pair['native_cross_backend_output_endpoint_match'] is False
    assert not pair['eligible_for_quality_transfer'] and not pair['eligible_for_claim_transfer']


@pytest.mark.parametrize('mutation', ['missing_sample', 'changed_sample', 'two_repetitions'])
def test_actual_sample_and_repetition_proof_is_required(saved_cases, tmp_path, mutation):
    case = copy.deepcopy(saved_cases[0]); original = Path(case['result_path'])
    folder = tmp_path/'result'; shutil.copytree(original.parent, folder)
    path = folder/original.name; payload = json.loads(path.read_text())
    if mutation == 'two_repetitions':
        payload['repetitions'] = payload['repetitions'][:2]; path.write_text(json.dumps(payload))
    else:
        sample = folder/next(iter(payload['repetitions'][0]['raw_output_samples'].values()))['path']
        if mutation == 'missing_sample': sample.unlink()
        else: sample.write_bytes(sample.read_bytes() + b'changed')
    observation = observed(saved_cases[0]); observation['result_path'] = str(path)
    pair = completion_pair(observation, case)
    assert not pair['eligible_for_technical_transfer']
    assert pair['native_generic_completed_endpoint_evidence']['status'] == 'unverified'
